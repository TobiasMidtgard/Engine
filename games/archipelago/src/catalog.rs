//! charged items, two-edged items, and the gear and captains of vessels. [`crate::items`]
//! joins it to the first half; an item is known by its place in the joined table.
//!
//! Items marked `later` are in the catalogue already but only start working with the round
//! that brings what they answer (fires, riots and sickness in round 8; pirates, warships and
//! damage at sea in round 9). The pedlar and the sea never hand them out before then.

