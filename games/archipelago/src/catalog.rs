/// One row: the fields every item has.
#[allow(clippy::too_many_arguments)]
const fn row(
    name: &'static str,
    host: Host,
    sort: Sort,
    rank: Rank,
    icon: Icon,
    on: &'static [Kind],
    effects: &'static [Effect],
    way: Way,
    blurb: &'static str,
) -> ItemDef {
    ItemDef {
        name,
        blurb,
        host,
        sort,
        rank,
        guild: None,
        home: None,
        on,
        effects,
        icon,
        way,
        burst: &[],
        drive: None,
        later: 0,
    }
}

const P: Way = Way::Passive;
const TWO: Way = Way::TwoEdged;
const fn order(lasts_s: f32, cooldown_s: f32) -> Way {
    Way::Order {
        lasts_s,
        cooldown_s,
    }
}
const fn used(charges: u32, lasts_s: f32) -> Way {
    Way::Consumable { charges, lasts_s }
}
const fn cue(on: Cue, lasts_s: f32, recharge_s: f32) -> Way {
    Way::Triggered {
        on,
        lasts_s,
        recharge_s,
    }
}
const fn charged(fill: Fill, need: f32, lasts_s: f32) -> Way {
    Way::Charged {
        fill,
        need,
        lasts_s,
    }
}

