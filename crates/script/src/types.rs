//! `engine.d.luau`: Luau type definitions of everything scripts can call, for luau-lsp (VS Code
//! and other editors autocomplete and check scripts against it).
//!
//! The engine's functions come from the API registry: each one's argument type is inferred from
//! its JSON example (every field optional, since components and arguments default), and its
//! summary becomes the doc comment.

