/// The Luau type of a JSON example value.
fn luau_type(v: &Value, indent: usize) -> String {
    match v {
        Value::Null => "any".into(),
        Value::Bool(_) => "boolean".into(),
        Value::Number(_) => "number".into(),
        Value::String(_) => "string".into(),
        Value::Array(items) => {
            if items.len() == 3 && items.iter().all(|i| i.is_number()) {
                "Vec3 | { number }".into()
            } else if let Some(first) = items.first() {
                format!("{{ {} }}", luau_type(first, indent))
            } else {
                "{ any }".into()
            }
        }
        Value::Object(map) => {
            if map.is_empty() {
                return "{ [string]: any }".into();
            }
            let pad = "\t".repeat(indent + 1);
            let mut s = String::from("{\n");
            for (k, v) in map {
                let key = if k.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
                    && !k.starts_with(|c: char| c.is_ascii_digit())
                {
                    k.clone()
                } else {
                    format!("[\"{k}\"]")
                };
                let _ = writeln!(s, "{pad}{key}: ({})?,", luau_type(v, indent + 1));
            }
            s.push_str(&"\t".repeat(indent));
            s.push('}');
            s
        }
    }
}

fn comment(text: &str, indent: usize) -> String {
    let pad = "\t".repeat(indent);
    text.lines()
        .map(|l| format!("{pad}--- {}\n", l.trim()))
        .collect()
}

/// A namespace's members: functions, and sub-namespaces (`physics.proving_ground.replay`).
#[derive(Default)]
struct Ns {
    funcs: BTreeMap<String, (String, String)>,
    subs: BTreeMap<String, Ns>,
}

/// A table type's key: the name, or `["name"]` for one of Luau's reserved words
/// (`script.break` is `script["break"]` in a script).
fn key(name: &str) -> String {
    const RESERVED: &[&str] = &[
        "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
        "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while",
    ];
    if RESERVED.contains(&name) {
        format!("[\"{name}\"]")
    } else {
        name.to_string()
    }
}

fn write_ns(out: &mut String, ns: &Ns, indent: usize) {
    let pad = "\t".repeat(indent);
    for (name, (summary, args)) in &ns.funcs {
        out.push_str(&comment(summary, indent));
        let ty = serde_json::from_str::<Value>(args)
            .map(|v| luau_type(&v, indent))
            .unwrap_or_else(|_| "any".into());
        let _ = writeln!(out, "{pad}{}: (args: ({ty})?) -> any,", key(name));
    }
    for (name, sub) in &ns.subs {
        let _ = writeln!(out, "{pad}{}: {{", key(name));
        write_ns(out, sub, indent + 1);
        let _ = writeln!(out, "{pad}}},");
    }
}

/// The whole definitions file for this world's registry.
pub fn definitions(world: &World) -> String {
    let mut out = String::from(BUILTINS);
    let mut tops: BTreeMap<String, Ns> = BTreeMap::new();
    if let Some(api) = world.get_resource::<ApiRegistry>() {
        for e in api.list() {
            let mut parts = e.name.split('.');
            let Some(top) = parts.next() else { continue };
            let rest: Vec<&str> = parts.collect();
            let Some((last, middle)) = rest.split_last() else {
                continue;
            };
            let mut ns = tops.entry(top.to_string()).or_default();
            for m in middle {
                ns = ns.subs.entry(m.to_string()).or_default();
            }
            ns.funcs.insert(
                last.to_string(),
                (e.summary.clone(), e.args_example.clone()),
            );
        }
    }
    out.push_str("-- Engine functions, one table per module (from the API registry).\n\n");
    for (top, ns) in &tops {
        if top == "input" {
            out.push_str(
                "declare input: {\n\tpressed: (action: string) -> boolean,\n\tjust_pressed: \
                 (action: string) -> boolean,\n\tjust_released: (action: string) -> boolean,\n\t\
                 value: (action: string) -> number,\n\tstick: (action: string) -> (number, number),\n",
            );
        } else {
            let _ = writeln!(out, "declare {top}: {{");
        }
        write_ns(&mut out, ns, 1);
        out.push_str("}\n\n");
    }
    if let Some(types) = world.get_resource::<TypeRegistry>() {
        out.push_str("-- Registered components (for entity:get / entity:set), with their docs:\n");
        for c in types.components() {
            let doc = c.doc.lines().next().unwrap_or("");
            let _ = writeln!(out, "--   {}: {}", c.name, doc);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn json_examples_become_luau_types() {
        assert_eq!(luau_type(&json!([1, 2, 3]), 0), "Vec3 | { number }");
        let t = luau_type(&json!({"at": [0, 0, 0], "radius": 1.5, "tags": ["a"]}), 0);
        assert!(t.contains("at: (Vec3 | { number })?"), "{t}");
        assert!(t.contains("radius: (number)?"), "{t}");
        assert!(t.contains("tags: ({ string })?"), "{t}");
    }
}
