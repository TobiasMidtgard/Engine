//! The face, neck and torso sliders: MakeHuman's modeling modifiers (CC0), listed from its
//! `data/modifiers/modeling_modifiers.json`. Each slider runs -1..1 between its `low` and `high`
//! target (0..1 for one-sided ones).

/// One shape slider: its group (UI section), key (`Appearance::shape`), and the target
/// suffixes at -1 and +1 (empty `low` for one-sided sliders).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Slider {
    pub group: &'static str,
    pub target: &'static str,
    pub low: &'static str,
    pub high: &'static str,
}

impl Slider {
    /// Key in `Appearance::shape`: the target, plus `-low|high` for two-sided sliders
    /// (`nose-hump-decr|incr`), as MakeHuman names them.
    pub fn key(&self) -> String {
        if self.low.is_empty() {
            self.target.to_string()
        } else {
            format!("{}-{}|{}", self.target, self.low, self.high)
        }
    }
}

