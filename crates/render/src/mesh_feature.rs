fn set_bit(bits: &mut Vec<u64>, index: u32) {
    let word = index as usize / 64;
    if word >= bits.len() {
        bits.resize(word + 1, 0);
    }
    bits[word] |= 1 << (index % 64);
}

/// Run jobs on the engine's compute pool (`engine_core::tasks`), the calling thread taking
/// part; in turn for a single job or without a pool.
///
/// The calling thread runs the first job itself, before it waits: a scope's thread otherwise
/// starts by ticking the pool's queue, where it may pick up another system's long task while
/// the render waits.
fn run_jobs<'env, F: FnOnce() + Send + 'env>(jobs: impl Iterator<Item = F>) {
    let mut jobs = jobs.peekable();
    let Some(first) = jobs.next() else {
        return;
    };
    match engine_core::tasks::ComputeTaskPool::try_get() {
        Some(pool) if jobs.peek().is_some() => {
            pool.scope(|scope| {
                for job in jobs {
                    scope.spawn(async move { job() });
                }
                first();
            });
        }
        _ => {
            first();
            jobs.for_each(|job| job());
        }
    }
}

/// Whether a caster with this camera-relative bounding sphere belongs in shadow map `map`'s
/// static image: anywhere in its square (or box), whatever the camera looks at.
fn map_holds(view: &ViewData, map: usize, center: Vec3, radius: f32) -> bool {
    match map {
        SKY_OCCLUSION_VIEW => {
            view.sky_occlusion.enabled && view.sky_occlusion.contains_sphere(center, radius)
        }
        FAR_SHADOW_MAP => {
            view.sun_shadows && view.far_shadow.enabled && view.far_shadow.casts(center, radius)
        }
        c => {
            view.sun_shadows
                && c < (view.cascades.count as usize).min(MAX_CASCADES)
                && view.cascades.sphere_in_square(c, center, radius)
        }
    }
}

/// Whether a caster with this camera-relative bounding sphere can cast into what map `map`
/// shades of this frame's view (the moving casters' cull).
fn map_shades(view: &ViewData, map: usize, center: Vec3, radius: f32) -> bool {
    match map {
        SKY_OCCLUSION_VIEW | FAR_SHADOW_MAP => map_holds(view, map, center, radius),
        c => view.cascades.sphere_in_cascade(c, center, radius),
    }
}

/// Whether shadow map `map`'s static image is drawn again this frame.
fn static_redraw(view: &ViewData, map: usize) -> bool {
    match map {
        SKY_OCCLUSION_VIEW => view.sky_occlusion.static_redraw,
        FAR_SHADOW_MAP => view.far_shadow.static_redraw,
        c => view.cascades.static_redraw[c],
    }
}

/// Whether a slot may take the cluster path (virtual geometry). Not while it dithers out
/// (`DitherFade`): the instanced path draws the dither.
fn cluster_candidate(hot: &Hot, mesh: &MeshFrame, mat: &MaterialFrame) -> bool {
    hot.flags & (mesh_scene::INSTANCED_ONLY | mesh_scene::SHADOW_ONLY) == 0
        && hot.dither == 0.0
        && mat.still_opaque
        && mesh.exists
        && (mesh.dense || hot.flags & mesh_scene::DISPLACED != 0)
}

/// The view and settings as the cull sees them.
#[derive(Clone, Copy)]
struct CullParams<'a> {
    view: &'a ViewData,
    /// Meters a pixel spans per meter of distance (none for orthographic views).
    pixel_meters: Option<f32>,
    lod_pixels: f32,
    min_pixels: f32,
    impostor_pixels: f32,
    shadows: bool,
    /// The camera's own view (not an extra one), its history kept: levels keep their
    /// hysteresis state and cross-fade.
    lod_fades: bool,
    /// This frame (low 32 bits).
    frame: u32,
}

struct Cull<'a> {
    p: CullParams<'a>,
    meshes: &'a FastMap<u32, GpuMesh>,
    impostors: Option<&'a Impostors>,
}

impl Cull<'_> {
    /// Out of the camera's view: it comes back at its level without a fade.
    fn unseen(&self, hot: &mut Hot) {
        if self.p.lod_fades {
            hot.lod = LOD_UNSET;
        }
    }

    /// An instance on the instanced path: left out (`None`) or an item to draw. Its world
    /// bounds are recomputed first when its transform or mesh changed.
    fn item(
        &self,
        slot: u32,
        hot: &mut Hot,
        cold: &Cold,
        mesh: &MeshFrame,
        mat: &MaterialFrame,
    ) -> Option<Item> {
        if hot.mesh_version != mesh.version {
            hot.center = cold.transform.transform_point(mesh.center.as_dvec3());
            hot.radius = mesh.radius * hot.scale;
            hot.mesh_version = mesh.version;
            // Its levels may have changed.
            hot.lod = LOD_UNSET;
        }
        let center = (hot.center - self.p.view.origin).as_vec3();
        let radius = hot.radius;
        let distance = center.length();
        if distance - radius > hot.max_distance || hot.dither.abs() >= 1.0 {
            self.unseen(hot);
            return None;
        }
        // Too small to cover a pixel: left out of the view (it may still cast a shadow).
        let meters_per_pixel = self
            .p
            .pixel_meters
            .map(|k| k * (distance - radius).max(self.p.view.near));
        let big_enough = meters_per_pixel.is_none_or(|m| 2.0 * radius >= self.p.min_pixels * m);
        let visible = big_enough
            && hot.flags & mesh_scene::SHADOW_ONLY == 0
            && self.p.view.frustum.intersects_sphere(center, radius);
        // Dithering out (`DitherFade`), it casts while at least half of it shows: one of a pair
        // swapping at a time (the one fading in takes over at the middle).
        let dither_casts = if hot.dither >= 0.0 {
            hot.dither < 0.5
        } else {
            hot.dither >= -0.5
        };
        let casts =
            self.p.shadows && hot.flags & mesh_scene::CASTS != 0 && !mat.blend && dither_casts;
        if !visible && !casts {
            self.unseen(hot);
            return None;
        }
        let full_detail = hot.flags & mesh_scene::FULL_DETAIL != 0;
        let lod = match (meters_per_pixel, self.meshes.get(&mesh.index)) {
            (Some(m), Some(g)) if self.p.lod_pixels > 0.0 && !full_detail => {
                let tolerance = self.p.lod_pixels * m;
                if self.p.lod_fades && hot.lod != LOD_UNSET {
                    // Hysteresis: keep the level while it is within a band around the
                    // threshold, so a mesh standing at one doesn't flip back and forth.
                    let finest = crate::mesh_lod::pick(g.errors(), hot.scale, tolerance / LOD_BAND);
                    let coarsest =
                        crate::mesh_lod::pick(g.errors(), hot.scale, tolerance * LOD_BAND);
                    hot.lod.clamp(finest, coarsest)
                } else {
                    crate::mesh_lod::pick(g.errors(), hot.scale, tolerance)
                }
            }
            _ => 0,
        };
        // A new level cross-fades in over the old one (both drawn, complementary dither), as
        // Unreal's dithered LOD transitions and Unity's LOD cross-fade do.
        let (lod_from, lod_fade) = if !visible {
            self.unseen(hot);
            (lod, 0.0)
        } else if self.p.lod_fades {
            if hot.lod != lod {
                if hot.lod != LOD_UNSET && hot.dither == 0.0 {
                    hot.lod_from = hot.lod;
                    hot.lod_frame = self.p.frame;
                } else {
                    hot.lod_from = lod;
                }
                hot.lod = lod;
            }
            let age = self.p.frame.wrapping_sub(hot.lod_frame);
            if hot.lod_from != lod && age < LOD_FADE_FRAMES && hot.dither == 0.0 {
                (
                    hot.lod_from,
                    ((age + 1) as f32 / (LOD_FADE_FRAMES + 1) as f32),
                )
            } else {
                hot.lod_from = lod;
                (lod, 0.0)
            }
        } else {
            (lod, 0.0)
        };
        // Far away, meshes whose levels of detail can't get cheap are drawn as impostors,
        // baked the first time one is that small. The bake keeps no emission, so glowing
        // materials stay meshes.
        let impostor_ok = self.p.impostor_pixels > 0.0
            && self.impostors.is_some()
            && !mat.blend
            && !mat.glows
            && mesh.impostor;
        // Size on screen in units of the impostor threshold: from 1 down to `IMPOSTOR_FADE`
        // both are drawn (the cross-fade), under that the impostor alone.
        let size = meters_per_pixel.map_or(f32::INFINITY, |m| {
            2.0 * radius / (self.p.impostor_pixels * m).max(f32::MIN_POSITIVE)
        });
        let impostor_size = size < 1.0;
        let impostor = self
            .impostors
            .filter(|_| impostor_ok)
            .zip(mat.impostor_key)
            .and_then(|(i, key)| i.layer((mesh.index, key)))
            .unwrap_or(crate::impostor::NONE);
        let baked = impostor != crate::impostor::NONE;
        let lod = if baked && size < IMPOSTOR_FADE {
            IMPOSTOR_LOD
        } else {
            lod
        };
        // A game's own fade (`DitherFade`) takes the dither's place: the impostor then swaps in
        // at the bottom of the cross-fade range without one.
        let fade = if baked && hot.dither == 0.0 && (IMPOSTOR_FADE..1.0).contains(&size) {
            ((1.0 - size) / (1.0 - IMPOSTOR_FADE)).max(f32::EPSILON)
        } else {
            0.0
        };
        let pipeline = if mat.blend { PIPE_BLEND } else { 0 }
            | if mat.double_sided { PIPE_DOUBLE } else { 0 }
            | if hot.flags & mesh_scene::MIRRORED != 0 {
                PIPE_MIRROR
            } else {
                0
            };
        // Impostors fade on their own; a level fade gives way to theirs.
        let (lod_from, lod_fade) = if lod == IMPOSTOR_LOD || fade > 0.0 {
            (lod, 0.0)
        } else {
            (lod_from, lod_fade)
        };
        Some(Item {
            slot,
            mesh: mesh.index,
            page: mesh.page,
            lod,
            lod_from,
            lod_fade,
            scale: hot.scale,
            full_detail,
            impostor,
            pipeline,
            // Set after the cull, with the material slot.
            textures: 0,
            masked: mat.masked,
            visible,
            casts,
            center,
            radius,
            dist2: center.length_squared(),
            material: hot.material,
            material_slot: 0,
            impostor_ok,
            impostor_size,
            fade,
            dither: hot.dither,
            since: if mesh.skinned || hot.dither != 0.0 {
                u64::MAX
            } else {
                cold.changed.max(mesh.uploaded) + STILL_FRAMES
            },
            sways: mat.sways,
        })
    }
}

impl Item {
    /// Opaque first, by pipeline, texture set, pool page, mesh and level; then transparent,
    /// farthest first.
    ///
    /// Texture set ids, pages and mesh indices beyond 18, 6 and 24 bits share keys: such items
    /// may interleave and split batches, never draw wrong (batches compare whole keys).
    fn sort_key(&self) -> u64 {
        if self.pipeline & PIPE_BLEND != 0 {
            1 << 63 | (!self.dist2.to_bits()) as u64
        } else {
            (self.pipeline as u64) << 60
                | (self.textures as u64 & 0x3_ffff) << 42
                | (self.page as u64 & 0x3f) << 36
                | (self.mesh as u64 & 0xff_ffff) << 12
                | self.lod as u64
        }
    }
}

/// Where a [`Displacement`]'s height comes from, before it is read (cheap to find every
/// frame; reading it happens once, when a build starts).
enum HeightSource {
    /// A procedural or code height, with its cache key.
    Field(Arc<dyn HeightField>, u64),
    /// The material's height texture at an asset version.
    Image(Handle<Image>, u64),
    /// The generated height map of the material's preset, at a size.
    Preset(MaterialPreset, u32),
}

fn height_source(
    d: &Displacement,
    material: &StandardMaterial,
    images: Option<&Assets<Image>>,
    preset_size: u32,
) -> Option<HeightSource> {
    match &d.source {
        DisplacementSource::Stone(f) => Some(HeightSource::Field(Arc::new(*f), f.key())),
        DisplacementSource::Custom(f) => Some(HeightSource::Field(f.field.clone(), f.key)),
        DisplacementSource::MaterialHeight => {
            if let Some(h) = material.height_texture {
                let images = images?;
                let h = images.canonical(h);
                let image = images.get(h)?;
                (!image.is_released()).then(|| HeightSource::Image(h, images.version(h)))
            } else {
                material
                    .preset
                    .map(|p| HeightSource::Preset(p, preset_size))
            }
        }
    }
}

/// Key of a displaced mesh's clusters: the mesh, the displacement and its height.
fn displaced_key(
    mesh: u32,
    d: &Displacement,
    material: &StandardMaterial,
    source: &HeightSource,
) -> u64 {
    let mut h = StableHasher::new(0xd15b_0001);
    h.write_u32(mesh);
    h.write_u64(d.settings_key());
    h.write_u32(d.amplitude_for(material).to_bits());
    match source {
        HeightSource::Field(_, key) => h.write_u64(*key),
        HeightSource::Image(handle, version) => {
            h.write_u32(handle.index());
            h.write_u64(*version);
        }
        HeightSource::Preset(p, size) => {
            h.write_u32(*p as u32 + 1000);
            h.write_u32(*size);
        }
    }
    if matches!(source, HeightSource::Image(..) | HeightSource::Preset(..)) {
        h.write_u32(material.mapping.key());
        h.write_u32(material.texture_scale.to_bits());
        h.write_u32(material.uv_scale[0].to_bits());
        h.write_u32(material.uv_scale[1].to_bits());
    }
    // Plain meshes use their asset index as the key; displaced keys have the top bit set.
    h.finish() | 1 << 63
}

/// The height field of a displacement, read when its build starts: the procedural one, or the
/// material's height map at the resolution its finest edges can use.
fn resolve_displacement(
    d: &Displacement,
    material: &StandardMaterial,
    source: &HeightSource,
    images: Option<&Assets<Image>>,
    preset_heights: &mut HashMap<(MaterialPreset, u32), Option<Image>>,
    gpu: &GpuShared,
) -> Option<DisplacedJob> {
    // Texels per tile so a texel is about half the finest edge.
    let repeat = material.uv_scale[0]
        .abs()
        .max(material.uv_scale[1].abs())
        .max(1e-4);
    let tile_m = material.texture_scale / repeat;
    let max_size = ((2.0 * tile_m / d.edge_m.max(1e-4)) as u32).clamp(64, 8192);
    let (field, field_key): (Arc<dyn HeightField>, u64) = match source {
        HeightSource::Field(f, key) => (f.clone(), *key),
        HeightSource::Image(handle, _) => {
            let image = HeightImage::from_image(images?.get(*handle)?, max_size)?;
            let field = MaterialHeightField::new(Arc::new(image), material);
            let key = field.key();
            (Arc::new(field), key)
        }
        HeightSource::Preset(preset, size) => {
            let maps = preset_heights.entry((*preset, *size)).or_insert_with(|| {
                gpu.read_material_maps(*preset, *size)
                    .map_err(|e| tracing::warn!("reading the {preset:?} height map failed: {e}"))
                    .ok()
                    .map(|m| m.height)
            });
            let image = HeightImage::from_image(maps.as_ref()?, max_size)?;
            let field = MaterialHeightField::new(Arc::new(image), material);
            let key = field.key();
            (Arc::new(field), key)
        }
    };
    Some(DisplacedJob {
        displacement: d.clone(),
        amplitude: d.amplitude_for(material),
        field,
        field_key,
    })
}

/// Largest scale along any axis (the longest basis vector; cheaper than decomposing).
pub(crate) fn max_scale(gt: &GlobalTransform) -> f32 {
    let m = gt.0.matrix3;
    m.x_axis
        .length_squared()
        .max(m.y_axis.length_squared())
        .max(m.z_axis.length_squared())
        .sqrt() as f32
}

/// The steps of the mesh feature's `prepare`: each a span for the frame profiler (`--profile`)
/// and a time for `Diagnostics` (`render.cpu.meshes: <step>`).
#[derive(Default)]
struct PrepareSteps {
    current: Option<(&'static str, std::time::Instant, tracing::span::EnteredSpan)>,
    done: Vec<(&'static str, f32)>,
}

impl PrepareSteps {
    /// End the current step and start `name`.
    fn step(&mut self, name: &'static str) {
        self.finish();
        let span = tracing::info_span!(target: "engine_render", "render_step", name).entered();
        self.current = Some((name, std::time::Instant::now(), span));
    }

    fn finish(&mut self) {
        if let Some((name, started, span)) = self.current.take() {
            drop(span);
            self.done
                .push((name, started.elapsed().as_secs_f32() * 1000.0));
        }
    }

    fn publish(mut self, diagnostics: Option<&mut Diagnostics>, gpu: &GpuShared) {
        self.finish();
        gpu.prepare_steps
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .extend_from_slice(&self.done);
        if let Some(d) = diagnostics {
            for (name, ms) in self.done {
                d.set(&format!("render.cpu.{name}"), ms as f64);
            }
        }
    }
}

