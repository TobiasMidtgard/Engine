/// instead of popping (as Unreal's dithered LOD transitions and Unity's LOD cross-fade do).
const IMPOSTOR_FADE: f32 = 0.7;
/// From this many shadow casters on, each shadow map's list is made on its own thread.
const PARALLEL_CASTERS: usize = 2000;
/// Slots (and instances) from which the gather's loops run on the worker threads.
const PARALLEL_GATHER: usize = 4096;
/// Frames a material keeps its slot after it was last drawn, so the render thread's cull
/// finds it (`MeshFeature::finish_items`).
const MATERIAL_KEEP_FRAMES: u64 = 2;

/// Threads for a pass over `slots` scene slots.
fn gather_threads(slots: usize) -> usize {
    if slots >= PARALLEL_GATHER {
        std::thread::available_parallelism().map_or(1, |n| n.get().min(8))
    } else {
        1
    }
}
/// Seconds between the profiler's mesh reports.
const PROFILE_REPORT_SECS: f32 = 10.0;

impl MeshFeature {
    /// Creates the scene, prepass and masked shadow pipelines this frame's batches use and
    /// that don't exist yet. Each costs a compile of the large mesh shader, so only the ones
    /// a scene draws with are made (a test app uses two or three of the 17).
    fn ensure_pipelines(&mut self, gpu: &GpuShared, warm: bool) {
        let mut main = [false; PIPELINE_VARIANTS as usize];
        let mut prepass = [false; PIPELINE_VARIANTS as usize];
        for b in self.opaque.iter() {
            main[b.key.pipeline as usize] = true;
            prepass[b.key.pipeline as usize] = true;
        }
        for b in self.transparent.iter() {
            main[b.key.pipeline as usize] = true;
        }
        let masked = self
            .shadow
            .iter()
            .chain(self.shadow_static.iter())
            .flatten()
            .any(|b| b.key.pipeline == SHADOW_MASKED);
        if warm && self.warmup.is_none() {
            self.start_warmup(gpu);
        }
        for variant in 0..PIPELINE_VARIANTS {
            let i = variant as usize;
            if main[i] && self.pipelines[i].is_none() {
                self.pipelines[i] = self.pipeline(gpu, PipelineKey::Main(variant));
            }
            if prepass[i] && self.prepass_pipelines[i].is_none() {
                self.prepass_pipelines[i] = self.pipeline(gpu, PipelineKey::Prepass(variant));
            }
        }
        if masked && self.shadow_masked_pipeline.is_none() {
            self.shadow_masked_pipeline = self.pipeline(gpu, PipelineKey::ShadowMasked);
        }
        if let Some(impostors) = &mut self.impostors {
            let constants = self.shader_features.mesh_constants();
            // The impostors' pipelines too: they are first needed when something far away is
            // baked, which is a first sight in play.
            if warm {
                impostors.start_warmup(gpu, &constants);
            }
            impostors.ensure_pipelines(gpu, &constants);
        }
    }

    /// Drops the pipelines built with other shader features; they are made again on use.
    fn clear_pipelines(&mut self) {
        // Built with the old features: unstarted ones are dropped, started ones thrown away.
        self.warmup = None;
        self.pipelines = (0..PIPELINE_VARIANTS).map(|_| None).collect();
        self.prepass_pipelines = (0..PIPELINE_VARIANTS).map(|_| None).collect();
        self.shadow_masked_pipeline = None;
        if let Some(impostors) = &mut self.impostors {
            impostors.clear_pipelines();
        }
    }

    /// What building the scene and prepass pipelines needs, owned (for the warm-up threads).
    fn mesh_inputs(&self, gpu: &GpuShared) -> Option<MeshPipelineInputs> {
        Some(MeshPipelineInputs {
            device: gpu.device.clone(),
            shader: self.shader.clone()?,
            layout: self.pipeline_layout.clone()?,
            hdr: gpu.formats.hdr,
            prepass_targets: gpu.prepass_targets(),
            depth: [gpu.depth_state(false), gpu.depth_state(true)],
            depth_equal: wgpu::DepthStencilState {
                depth_compare: Some(wgpu::CompareFunction::Equal),
                ..gpu.depth_state(false)
            },
            constants: self.shader_features.mesh_constants(),
        })
    }

    /// What building the alpha-tested shadow pipeline (masked casters) needs, owned.
    fn shadow_inputs(&self, gpu: &GpuShared) -> Option<ShadowPipelineInputs> {
        Some(ShadowPipelineInputs {
            device: gpu.device.clone(),
            shader: self.shadow_shader.clone()?,
            layout: self.shadow_masked_layout.clone()?,
            unclipped: gpu.features.contains(wgpu::Features::DEPTH_CLIP_CONTROL),
            depth: gpu.shadow_depth_state(),
            constants: self.shader_features.shadow_constants(),
        })
    }

    /// Queue every pipeline variant not built yet on the warm-up threads, the commonest
    /// first, so a frame finds them compiled.
    fn start_warmup(&mut self, gpu: &GpuShared) {
        let (Some(mesh), Some(shadow)) = (self.mesh_inputs(gpu), self.shadow_inputs(gpu)) else {
            return;
        };
        let mut jobs: Vec<(PipelineKey, Build)> = Vec::new();
        // Single-sided, double-sided, blended, then mirrored.
        for variant in [0, PIPE_DOUBLE, PIPE_BLEND, PIPE_BLEND | PIPE_DOUBLE]
            .into_iter()
            .flat_map(|v| [v, v | PIPE_MIRROR])
        {
            if self.pipelines[variant as usize].is_none() {
                let inputs = mesh.clone();
                jobs.push((
                    PipelineKey::Main(variant),
                    Box::new(move || Some(build_mesh_pipeline(&inputs, variant, false))),
                ));
            }
            // Blended surfaces have no prepass.
            if variant & PIPE_BLEND == 0 && self.prepass_pipelines[variant as usize].is_none() {
                let inputs = mesh.clone();
                jobs.push((
                    PipelineKey::Prepass(variant),
                    Box::new(move || Some(build_mesh_pipeline(&inputs, variant, true))),
                ));
            }
            if variant == PIPE_DOUBLE && self.shadow_masked_pipeline.is_none() {
                let inputs = shadow.clone();
                jobs.push((
                    PipelineKey::ShadowMasked,
                    Box::new(move || Some(build_shadow_masked_pipeline(&inputs))),
                ));
            }
        }
        let threads = std::thread::available_parallelism().map_or(2, |n| n.get() / 4);
        self.warmup = Some(Warmup::start("mesh pipelines", jobs, threads.clamp(1, 4)));
    }

    /// The pipeline for `key`: from the warm-up when it built it, else built now.
    fn pipeline(&mut self, gpu: &GpuShared, key: PipelineKey) -> Option<wgpu::RenderPipeline> {
        if let Some(warmup) = &mut self.warmup
            && let Taken::Ready(pipeline) = warmup.take(key)
        {
            return pipeline;
        }
        match key {
            PipelineKey::Main(v) => Some(build_mesh_pipeline(&self.mesh_inputs(gpu)?, v, false)),
            PipelineKey::Prepass(v) => Some(build_mesh_pipeline(&self.mesh_inputs(gpu)?, v, true)),
            PipelineKey::ShadowMasked => {
                Some(build_shadow_masked_pipeline(&self.shadow_inputs(gpu)?))
            }
        }
    }

    /// Give back the GPU space of meshes whose asset is gone (a streamed zone unloaded and
    /// freed its meshes): their vertices, indices and levels in the pool (pages left empty are
    /// released), and the levels still building. Cluster builds of a mesh nobody draws go after
    /// `EVICT_AFTER_FRAMES` (virtual_geometry/gpu.rs).
    fn forget_removed_meshes(&mut self, assets: &Assets<Mesh>) {
        let gone = |index: u32| !assets.contains(Handle::from_index(index));
        let pool = &mut self.pool;
        self.meshes.retain(|&index, mesh| {
            if gone(index) {
                mesh.free(pool);
                return false;
            }
            true
        });
        // A finished build of a mesh that is gone is never collected; its thread ends alone.
        self.lod_jobs.retain(|&index, _| !gone(index));
        self.lod_waiting.retain(|(index, _)| !gone(*index));
        self.warned_no_height.retain(|&index| !gone(index));
    }

    fn upload_mesh(&mut self, gpu: &GpuShared, index: u32, mesh: &Mesh, version: u64) {
        if let Some(old) = self.meshes.remove(&index) {
            old.free(&mut self.pool);
            // A mesh edited in place: static shadow images may show its old shape, but only
            // those drawn once it had been still long enough to join them (a mesh edited every
            // frame casts as a moving caster and never redraws them).
            for (dirty, &drawn) in self.static_dirty.iter_mut().zip(&self.image_frame) {
                *dirty |= old.uploaded + STILL_FRAMES <= drawn;
            }
        }
        if mesh.indices.is_empty() || mesh.vertices.is_empty() {
            return;
        }
        let aabb = mesh.aabb();
        let Some(pool) = self
            .pool
            .add(&gpu.device, &gpu.queue, &mesh.vertices, &mesh.indices)
        else {
            tracing::warn!(
                "mesh {index} ({} vertices) is larger than a GPU buffer may be",
                mesh.vertices.len()
            );
            return;
        };
        self.meshes.insert(
            index,
            GpuMesh {
                pool,
                version,
                center: aabb.center(),
                half_extents: aabb.half_extents(),
                min_y: aabb.min.y,
                height: (aabb.max.y - aabb.min.y).max(1e-3),
                last_used: self.frame,
                uploaded: self.frame,
                lods: Vec::new(),
            },
        );
    }

    /// Mark the static shadow images that hold a slot changed or dropped since (it was still
    /// when the image was drawn, and inside the map) to be drawn again.
    fn check_static_images(&mut self, view: &ViewData) {
        for change in self.shadow_changes.drain(..) {
            let center = (change.center - view.origin).as_vec3();
            for map in 0..SHADOW_MAPS {
                if self.static_dirty[map] || change.changed + STILL_FRAMES > self.image_frame[map] {
                    continue;
                }
                self.static_dirty[map] = map_holds(view, map, center, change.radius);
            }
        }
    }

    /// Start building the levels of detail of a mesh just uploaded (or queue it while the
    /// workers are busy).
    fn request_lods(&mut self, index: u32, handle: Handle<Mesh>, mesh: &Mesh, version: u64) {
        if mesh.indices.len() / 3 < crate::mesh_lod::MIN_TRIANGLES {
            return;
        }
        if self.lod_jobs.len() >= MAX_LOD_JOBS {
            if !self.lod_waiting.iter().any(|(i, _)| *i == index) {
                self.lod_waiting.push((index, handle));
            }
            return;
        }
        let mesh = mesh.clone();
        let job = std::thread::Builder::new()
            .name("mesh lods".into())
            .spawn(move || crate::mesh_lod::build(&mesh));
        match job {
            Ok(job) => {
                self.lod_jobs.insert(index, LodJob { version, job });
            }
            Err(e) => tracing::warn!("could not start building mesh levels of detail: {e}"),
        }
    }

    /// Upload the levels of detail that finished building, and start queued builds.
    fn collect_lods(&mut self, queue: &wgpu::Queue, meshes: &Assets<Mesh>) {
        let done: Vec<u32> = self
            .lod_jobs
            .iter()
            .filter(|(_, j)| j.job.is_finished())
            .map(|(i, _)| *i)
            .collect();
        for index in done {
            let Some(LodJob { version, job }) = self.lod_jobs.remove(&index) else {
                continue;
            };
            let Ok(levels) = job.join() else {
                tracing::warn!("building the levels of detail of mesh {index} failed");
                continue;
            };
            // A mesh changed meanwhile has been queued again by its upload.
            let Some(gpu_mesh) = self.meshes.get_mut(&index).filter(|m| m.version == version)
            else {
                continue;
            };
            // Finest first, as many as its page has room for.
            let page = gpu_mesh.pool.page;
            let pool = &mut self.pool;
            for l in gpu_mesh.lods.drain(..) {
                pool.free_indices(page, l.first_index, l.index_count);
            }
            gpu_mesh.lods = levels
                .into_iter()
                .map_while(|l| {
                    Some(GpuLod {
                        first_index: pool.add_indices(queue, page, &l.indices)?,
                        index_count: l.indices.len() as u32,
                        error: l.error,
                    })
                })
                .collect();
        }
        while self.lod_jobs.len() < MAX_LOD_JOBS
            && let Some((index, handle)) = self.lod_waiting.pop()
        {
            let version = meshes.version(handle);
            if let Some(mesh) = meshes.get(handle)
                && self
                    .meshes
                    .get(&index)
                    .is_some_and(|m| m.version == version)
            {
                self.request_lods(index, handle, mesh, version);
            }
        }
    }

    /// Material buffer slot and texture set id of a material, added to this frame's materials
    /// on first use.
    /// The cull of the instanced path, over every slot in parallel chunks, leaving out those
    /// the cluster path took and meshes not uploaded yet: this frame's `items` (their
    /// material slots still to set, `finish_items`), and how many were culled.
    fn cull(&mut self, view: &ViewData, settings: &RenderSettings) -> u32 {
        let params = CullParams {
            view,
            pixel_meters: crate::mesh_lod::meters_per_pixel(view.fov_y, view.height, 1.0),
            lod_pixels: settings.mesh_lod_pixels.max(0.0),
            min_pixels: settings.min_object_pixels.max(0.0),
            impostor_pixels: settings.impostor_pixels.max(0.0),
            shadows: view.sun_shadows || view.sky_occlusion.enabled,
            lod_fades: !view.extra_view && view.history_valid,
            frame: self.frame as u32,
        };
        let threads = gather_threads(self.scene.hot.len());
        let mut chunks = std::mem::take(&mut self.gather_scratch);
        chunks.resize_with(threads, Default::default);
        // Cleared here: a chunk gets no job when there are fewer slots than threads.
        for out in &mut chunks {
            out.items.clear();
            out.culled = 0;
            out.instanced.fill(0);
        }
        {
            let (mesh_frames, material_frames) = (&self.mesh_frames, &self.material_frames);
            let clustered = &self.cluster_slots;
            let cull = Cull {
                p: params,
                meshes: &self.meshes,
                impostors: self.impostors.as_ref(),
            };
            let gather = |base: usize, hot: &mut [Hot], cold: &[Cold], out: &mut GatherChunk| {
                for (k, (h, c)) in hot.iter_mut().zip(cold).enumerate() {
                    if h.flags & mesh_scene::VISIBLE == 0 {
                        continue;
                    }
                    let mesh = &mesh_frames[h.mesh as usize];
                    if mesh.version == 0 || !mesh.ready {
                        continue;
                    }
                    let slot = base + k;
                    if clustered
                        .get(slot / 64)
                        .is_some_and(|w| w >> (slot % 64) & 1 != 0)
                    {
                        continue;
                    }
                    let mat = &material_frames[h.material as usize];
                    set_bit(&mut out.instanced, h.mesh);
                    match cull.item(slot as u32, h, c, mesh, mat) {
                        Some(item) => out.items.push(item),
                        None => out.culled += 1,
                    }
                }
            };
            let scene = &mut self.scene;
            let per = scene.hot.len().div_ceil(threads).max(1);
            let gather = &gather;
            let parts = scene.hot.chunks_mut(per).zip(scene.cold.chunks(per));
            run_jobs(
                parts
                    .zip(chunks.iter_mut())
                    .enumerate()
                    .map(|(k, ((hot, cold), out))| move || gather(k * per, hot, cold, out)),
            );
        }
        let mut culled = 0;
        let mut items = std::mem::take(&mut self.items);
        let mut instanced = std::mem::take(&mut self.instanced_meshes);
        items.clear();
        instanced.clear();
        for chunk in &mut chunks {
            items.append(&mut chunk.items);
            culled += chunk.culled;
            if instanced.len() < chunk.instanced.len() {
                instanced.resize(chunk.instanced.len(), 0);
            }
            for (a, b) in instanced.iter_mut().zip(&chunk.instanced) {
                *a |= b;
            }
        }
        // Meshes drawn as instances stay uploaded.
        for (word, &bits) in instanced.iter().enumerate() {
            let mut bits = bits;
            while bits != 0 {
                let raw = word * 64 + bits.trailing_zeros() as usize;
                bits &= bits - 1;
                if let Some(gpu_mesh) = self.meshes.get_mut(&self.mesh_frames[raw].index) {
                    gpu_mesh.last_used = self.frame;
                }
            }
        }
        self.items = items;
        self.instanced_meshes = instanced;
        self.gather_scratch = chunks;
        culled
    }

    /// Material slots for the cull's items, impostor layers in use and bakes asked for. A
    /// material without a slot is set up from `assets` when the world is at hand (`prepare`);
    /// on the render thread its items wait a frame while the next `prepare` sets it up
    /// (`material_seen`). Returns how many items are culled (those waiting, and those only
    /// casting shadows).
    fn finish_items(
        &mut self,
        gpu: &GpuShared,
        assets: Option<(
            Option<&Assets<StandardMaterial>>,
            &TextureSources<'_>,
            &StandardMaterial,
        )>,
    ) -> u32 {
        let frame = self.frame;
        let mut culled = 0;
        let mut items = std::mem::take(&mut self.items);
        items.retain_mut(|item| {
            let index = item.material as usize;
            if self.material_seen.len() <= index {
                self.material_seen.resize(index + 1, 0);
            }
            self.material_seen[index] = frame;
            let (material_slot, textures) = match (self.material_frames[index].slot, &assets) {
                (Some(slot), _) => slot,
                (None, Some((material_assets, sources, default_material))) => {
                    let handle = Handle::from_index(self.material_frames[index].index);
                    let material = material_assets
                        .and_then(|m| m.get(handle))
                        .unwrap_or(default_material);
                    let slot = self.material_slot(gpu, handle.index() as u64, material, sources);
                    self.material_frames[index].slot = Some(slot);
                    slot
                }
                (None, None) => {
                    culled += 1;
                    return false;
                }
            };
            item.material_slot = material_slot;
            item.textures = textures;
            if item.impostor_ok
                && let Some(impostors) = &mut self.impostors
            {
                if item.impostor != crate::impostor::NONE {
                    impostors.mark_drawn(item.impostor);
                } else if item.visible && item.impostor_size {
                    // Baked with the material's images, once they have all loaded.
                    let loaded = self
                        .texture_sets
                        .get(textures as usize)
                        .and_then(Option::as_ref)
                        .is_some_and(TextureSet::complete);
                    if loaded && let Some(key) = self.material_frames[index].impostor_key {
                        let hot = &self.scene.hot[item.slot as usize];
                        let mesh = &self.mesh_frames[hot.mesh as usize];
                        impostors.request(
                            (item.mesh, key),
                            crate::impostor::Request {
                                mesh: item.mesh,
                                material_slot,
                                textures,
                                center: mesh.center,
                                radius: mesh.radius,
                                score: mesh.coarsest as u64,
                            },
                        );
                    }
                }
            }
            if !item.visible {
                culled += 1;
            }
            true
        });
        self.items = items;
        culled
    }

    fn material_slot(
        &mut self,
        gpu: &GpuShared,
        handle: u64,
        material: &StandardMaterial,
        sources: &TextureSources,
    ) -> (u32, u32) {
        if let Some(v) = self.material_index.get(&handle) {
            return *v;
        }
        let textures = self.texture_set_for(gpu, material, sources);
        let mut gpu_material = material.to_gpu();
        // Only claim the slots that have a real image bound (others may still load).
        let set = self
            .texture_sets
            .get(textures as usize)
            .and_then(Option::as_ref);
        let bound = set.map_or(0, TextureSet::flags);
        let (vt_low, vt_high) = set.map_or((0, 0), TextureSet::virtual_ids);
        gpu_material.flags[0] = (gpu_material.flags[0] & !TEXTURE_FLAGS) | bound;
        gpu_material.flags[1] = vt_low;
        gpu_material.flags[2] = vt_high;
        let slot = self.material_data.len() as u32;
        self.material_data.push(gpu_material);
        self.material_index.insert(handle, (slot, textures));
        (slot, textures)
    }

    /// With `--profile`: where the instanced path's triangles go, per pass and per mesh (the
    /// heaviest first), so a scene's costliest meshes can be found and simplified.
    fn triangle_report(&self, shadows: bool) -> String {
        use std::fmt::Write as _;
        let tris = |b: &Batch| {
            self.meshes
                .get(&b.key.mesh)
                .map_or(0, |m| (m.level(b.key.lod).1 / 3) as u64 * b.count as u64)
        };
        let sum = |batches: &[Batch]| batches.iter().map(tris).sum::<u64>();
        let mut out = String::new();
        let view = sum(&self.opaque) + sum(&self.transparent);
        let _ = write!(
            out,
            "view {:.2} M + {} impostors",
            view as f64 / 1e6,
            self.impostor_view.1
        );
        if shadows {
            // Moving casters every frame; the still ones when their static image was last
            // drawn (how many frames ago).
            for (c, s) in self.shadow.iter().enumerate() {
                let name = match c {
                    SKY_OCCLUSION_VIEW => "sky occlusion".to_string(),
                    FAR_SHADOW_MAP => "far shadow".to_string(),
                    _ => format!("cascade {c}"),
                };
                let _ = write!(
                    out,
                    ", {name} {:.2} M + {:.2} M still ({} frames ago)",
                    sum(s) as f64 / 1e6,
                    self.static_triangles[c] as f64 / 1e6,
                    self.frame.saturating_sub(self.image_frame[c])
                );
            }
        }
        if let Some(c) = &self.clusters {
            let _ = write!(out, "; clusters {:.2} M", c.stats().triangles as f64 / 1e6);
        }
        out.push('\n');
        // Per mesh: instances in the view and in all shadow passes.
        let mut per_mesh: HashMap<u32, [u64; 2]> = HashMap::new();
        for b in self.opaque.iter().chain(&self.transparent) {
            per_mesh.entry(b.key.mesh).or_default()[0] += b.count as u64;
        }
        for b in self.shadow.iter().chain(&self.shadow_static).flatten() {
            per_mesh.entry(b.key.mesh).or_default()[1] += b.count as u64;
        }
        let mut rows: Vec<_> = per_mesh
            .iter()
            .filter_map(|(m, n)| {
                let g = self.meshes.get(m)?;
                let t = (g.pool.index_count / 3) as u64;
                Some((*m, t, *n, g.half_extents * 2.0, t * (n[0] + n[1])))
            })
            .collect();
        rows.sort_by_key(|r| std::cmp::Reverse(r.4));
        let _ = writeln!(
            out,
            "  mesh    tris each  in view  in shadows  total M  size m"
        );
        for (m, t, n, size, total) in rows.iter().take(15) {
            let _ = writeln!(
                out,
                "  {m:<6} {t:>10} {:>8} {:>11} {:>8.2}  {:.1} x {:.1} x {:.1}",
                n[0],
                n[1],
                *total as f64 / 1e6,
                size.x,
                size.y,
                size.z
            );
        }
        out
    }

    fn batch(keys: &[BatchKey], first: u32, out: &mut Vec<Batch>) {
        let mut i = 0;
        while i < keys.len() {
            let key = keys[i];
            let start = i;
            while i < keys.len() && keys[i] == key {
                i += 1;
            }
            out.push(Batch {
                key,
                first: first + start as u32,
                count: (i - start) as u32,
                args: NO_ARGS,
            });
        }
    }

    /// Texture set id for a material (0 for untextured materials), creating or rebuilding the
    /// bind group when its images changed. `preset_size` is the resolution of generated preset
    /// maps.
    fn texture_set_for(
        &mut self,
        gpu: &GpuShared,
        material: &StandardMaterial,
        sources: &TextureSources,
    ) -> u32 {
        let TextureSources {
            images,
            registry,
            settings,
        } = *sources;
        let preset_size = settings.material_texture_size;
        let mut handles = material.textures();
        if handles.iter().all(Option::is_none) && material.preset.is_none() {
            return 0;
        }
        // Two handles naming the same image (a forwarded reservation) share one upload.
        if let Some(images) = images {
            for h in handles.iter_mut().flatten() {
                *h = images.canonical(*h);
            }
        }
        let generated = material
            .preset
            .map(|p| gpu.material_textures(p, preset_size));
        let key: TextureSetKey = (
            handles.map(|h| h.map(|h| h.index())),
            generated.as_ref().map(|g| (g.preset, g.size)),
        );
        let mut bound: [Option<Bound>; TEXTURE_SLOTS] = [None; TEXTURE_SLOTS];
        let mut textures: [Option<Arc<ImageTexture>>; TEXTURE_SLOTS] = Default::default();
        for (slot, handle) in handles.iter().enumerate() {
            let Some(handle) = handle else {
                // Slots the material leaves empty take the preset's map, if it has one.
                if let Some(g) = &generated
                    && preset_map(g, slot).is_some()
                {
                    bound[slot] = Some(Bound::Generated(g.id));
                }
                continue;
            };
            let Some(images) = images else {
                continue;
            };
            // Streamed: drawn through the virtual texture cache once its root tile is in.
            if let Some(vt) = &mut self.vt {
                if let Some(id) =
                    vt.texture_for(images, registry, *handle, COLOR_SLOT[slot], settings)
                {
                    bound[slot] = Some(Bound::Virtual(id));
                    continue;
                }
                if vt.is_pending_image(images, registry, *handle, settings) {
                    continue;
                }
            }
            if let Some(texture) = gpu.image_texture_for(images, *handle, SLOT_USE[slot]) {
                bound[slot] = Some(Bound::Image(texture.id));
                textures[slot] = Some(texture);
            }
        }
        let id = match self.texture_set_ids.get(&key) {
            Some(id) => *id,
            None => {
                let id = self
                    .free_set_ids
                    .pop()
                    .unwrap_or(self.texture_sets.len() as u32);
                self.texture_set_ids.insert(key, id);
                id
            }
        };
        let vt_generation = self.vt.as_ref().map_or(0, |v| v.bind_generation());
        let needs_build = self
            .texture_sets
            .get(id as usize)
            .and_then(Option::as_ref)
            .is_none_or(|s| s.bound != bound || s.vt_generation != vt_generation);
        if needs_build {
            let views: [&wgpu::TextureView; TEXTURE_SLOTS] = std::array::from_fn(|slot| {
                match bound[slot] {
                    Some(Bound::Image(_)) => textures[slot].as_ref().map(|t| &t.view),
                    Some(Bound::Generated(_)) => {
                        generated.as_deref().and_then(|g| preset_map(g, slot))
                    }
                    Some(Bound::Virtual(_)) | None => None,
                }
                .unwrap_or(&self.default_textures[slot].1)
            });
            let (Some(layout), Some(sampler), Some(vt)) =
                (&self.texture_layout, &self.sampler, &self.vt)
            else {
                return 0;
            };
            let group = create_texture_group(&gpu.device, layout, sampler, views, vt);
            if self.texture_sets.len() <= id as usize {
                self.texture_sets.resize_with(id as usize + 1, || None);
            }
            self.texture_sets[id as usize] = Some(TextureSet {
                group,
                key,
                bound,
                vt_generation,
                last_used: self.frame,
            });
        } else if let Some(Some(set)) = self.texture_sets.get_mut(id as usize) {
            set.last_used = self.frame;
        }
        id
    }

    /// Release texture sets nobody used for a while (the images themselves live in the shared
    /// image cache, which evicts them).
    fn evict(&mut self) {
        let frame = self.frame;
        for id in 1..self.texture_sets.len() {
            let stale = self.texture_sets[id]
                .as_ref()
                .is_some_and(|s| s.last_used + EVICT_AFTER_FRAMES < frame);
            if stale && let Some(set) = self.texture_sets[id].take() {
                self.texture_set_ids.remove(&set.key);
                self.free_set_ids.push(id as u32);
            }
        }
    }

    /// (Re)build texture set 0, the default set of untextured materials.
    fn build_default_set(&mut self, device: &wgpu::Device) {
        let (Some(layout), Some(sampler), Some(vt)) =
            (&self.texture_layout, &self.sampler, &self.vt)
        else {
            return;
        };
        let views: [&wgpu::TextureView; TEXTURE_SLOTS] =
            std::array::from_fn(|slot| &self.default_textures[slot].1);
        let group = create_texture_group(device, layout, sampler, views, vt);
        let set = TextureSet {
            group,
            key: ([None; TEXTURE_SLOTS], None),
            bound: [None; TEXTURE_SLOTS],
            vt_generation: vt.bind_generation(),
            last_used: 0,
        };
        match self.texture_sets.first_mut() {
            Some(first) => *first = Some(set),
            None => self.texture_sets.push(Some(set)),
        }
    }

    fn texture_group(&self, id: u32) -> Option<&wgpu::BindGroup> {
        self.texture_sets
            .get(id as usize)
            .and_then(Option::as_ref)
            .or_else(|| self.texture_sets.first().and_then(Option::as_ref))
            .map(|s| &s.group)
    }

    /// Draw a shadow view's batches and, with `with_clusters`, its clusters (`view`: a cascade,
    /// `SKY_OCCLUSION_VIEW` or `FAR_SHADOW_CLUSTERS`). Clusters are culled on the GPU every
    /// frame, so they are drawn with the moving casters, never into a static image.
    fn draw_shadow_view(
        &self,
        pass: &mut wgpu::RenderPass<'_>,
        batches: &[Batch],
        view: usize,
        impostors: (u32, u32),
        with_clusters: bool,
    ) {
        let (Some(group), Some(instances)) = (&self.material_group, &self.instances) else {
            return;
        };
        let clusters = self
            .clusters
            .as_ref()
            .filter(|c| with_clusters && c.is_active());
        if batches.is_empty() && clusters.is_none() && impostors.1 == 0 {
            return;
        }
        pass.set_bind_group(1, group, &[]);
        pass.set_vertex_buffer(1, instances.buffer.slice(..));
        let pipeline_for = |p: u8| match p {
            SHADOW_MASKED => self.shadow_masked_pipeline.as_ref(),
            _ => self.shadow_pipeline.as_ref(),
        };
        self.draw_batches(pass, batches, pipeline_for, |p| p == SHADOW_MASKED);
        if let Some(i) = &self.impostors {
            i.draw_shadow(pass, impostors);
        }
        if let Some(clusters) = clusters {
            clusters.draw_shadow(pass, view);
        }
    }

    fn draw_batches<'a>(
        &'a self,
        pass: &mut wgpu::RenderPass<'_>,
        batches: &[Batch],
        pipeline_for: impl Fn(u8) -> Option<&'a wgpu::RenderPipeline>,
        bind_textures: impl Fn(u8) -> bool,
    ) {
        let mut current_pipeline = u8::MAX;
        let mut current_textures = u32::MAX;
        let mut current_page = u16::MAX;
        let indirect = self.indirect.as_ref().filter(|_| self.multi_draw);
        let mut i = 0;
        while i < batches.len() {
            let b = &batches[i];
            let run = self.run_len(batches, i, &bind_textures);
            i += run;
            let Some(mesh) = self.meshes.get(&b.key.mesh) else {
                continue;
            };
            let Some(pipeline) = pipeline_for(b.key.pipeline) else {
                continue;
            };
            if b.key.pipeline != current_pipeline {
                pass.set_pipeline(pipeline);
                current_pipeline = b.key.pipeline;
                current_textures = u32::MAX;
            }
            if bind_textures(b.key.pipeline) && b.key.textures != current_textures {
                if let Some(group) = self.texture_group(b.key.textures) {
                    pass.set_bind_group(2, group, &[]);
                }
                current_textures = b.key.textures;
            }
            if mesh.pool.page != current_page {
                let Some((vertex, index)) = self.pool.buffers(mesh.pool.page) else {
                    continue;
                };
                pass.set_vertex_buffer(0, vertex.slice(..));
                pass.set_index_buffer(index.slice(..), wgpu::IndexFormat::Uint32);
                current_page = mesh.pool.page;
            }
            if let Some(indirect) = indirect {
                pass.multi_draw_indexed_indirect(
                    &indirect.buffer,
                    b.args as u64 * std::mem::size_of::<DrawArgs>() as u64,
                    run as u32,
                );
                continue;
            }
            let (first, count) = mesh.level(b.key.lod);
            pass.draw_indexed(
                first..first + count,
                mesh.pool.base_vertex as i32,
                b.first..b.first + b.count,
            );
        }
    }

    /// How many batches from `i` on go out as one multi-draw: the same pipeline, texture set
    /// (where the pass binds them) and pool page, with their arguments one after another (1
    /// without multi-draw).
    fn run_len(&self, batches: &[Batch], i: usize, bind_textures: impl Fn(u8) -> bool) -> usize {
        let b = &batches[i];
        let page = |b: &Batch| self.meshes.get(&b.key.mesh).map(|m| m.pool.page);
        if !self.multi_draw || b.args == NO_ARGS {
            return 1;
        }
        let textures = bind_textures(b.key.pipeline);
        let first_page = page(b);
        batches[i + 1..]
            .iter()
            .zip(1..)
            .take_while(|(c, n)| {
                c.key.pipeline == b.key.pipeline
                    && (!textures || c.key.textures == b.key.textures)
                    && c.args == b.args.wrapping_add(*n)
                    && page(c) == first_page
            })
            .count()
            + 1
    }

    /// Indirect arguments for every batch list, in list order, so batches drawn one after
    /// another can share a multi-draw.
    fn write_draw_args(&mut self, gpu: &GpuShared, settings: &RenderSettings) {
        self.multi_draw = settings.multi_draw_indirect
            && gpu
                .device
                .features()
                .contains(wgpu::Features::INDIRECT_FIRST_INSTANCE);
        self.args.clear();
        let (meshes, args) = (&self.meshes, &mut self.args);
        let lists = [&mut self.opaque, &mut self.transparent]
            .into_iter()
            .chain(self.shadow.iter_mut())
            .chain(self.shadow_static.iter_mut());
        for b in lists.flatten() {
            b.args = match meshes.get(&b.key.mesh).filter(|_| self.multi_draw) {
                Some(m) => {
                    let (first_index, index_count) = m.level(b.key.lod);
                    args.push(DrawArgs {
                        index_count,
                        instance_count: b.count,
                        first_index,
                        base_vertex: m.pool.base_vertex as i32,
                        first_instance: b.first,
                    });
                    (args.len() - 1) as u32
                }
                None => NO_ARGS,
            };
        }
        if self.multi_draw && !self.args.is_empty() {
            self.indirect
                .get_or_insert_with(|| {
                    GrowBuffer::new(
                        &gpu.device,
                        "mesh draw arguments",
                        wgpu::BufferUsages::INDIRECT,
                        1 << 16,
                    )
                })
                .write(&gpu.device, &gpu.queue, bytemuck::cast_slice(&self.args));
        }
    }

    /// Draw commands a batch list goes out as.
    fn commands(&self, batches: &[Batch], bind_textures: impl Fn(u8) -> bool) -> u32 {
        let (mut i, mut n) = (0, 0);
        while i < batches.len() {
            i += self.run_len(batches, i, &bind_textures);
            n += 1;
        }
        n
    }
}

/// A pipeline variant of the mesh feature (for the warm-up).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
enum PipelineKey {
    Main(u8),
    Prepass(u8),
    ShadowMasked,
}

#[derive(Clone)]
struct MeshPipelineInputs {
    device: wgpu::Device,
    shader: wgpu::ShaderModule,
    layout: wgpu::PipelineLayout,
    hdr: wgpu::TextureFormat,
    prepass_targets: [Option<wgpu::ColorTargetState>; 2],
    /// Depth state without and with depth writes.
    depth: [wgpu::DepthStencilState; 2],
    /// The opaque scene pass: no writes, equal to the prepass's depth.
    depth_equal: wgpu::DepthStencilState,
    constants: [(&'static str, f64); 2],
}

#[derive(Clone)]
struct ShadowPipelineInputs {
    device: wgpu::Device,
    shader: wgpu::ShaderModule,
    layout: wgpu::PipelineLayout,
    unclipped: bool,
    depth: wgpu::DepthStencilState,
    constants: [(&'static str, f64); 1],
}

/// A scene (or, with `prepass`, depth prepass) pipeline for `variant`'s `PIPE_*` bits.
fn build_mesh_pipeline(
    inputs: &MeshPipelineInputs,
    variant: u8,
    prepass: bool,
) -> wgpu::RenderPipeline {
    let blend = !prepass && variant & PIPE_BLEND != 0;
    // The opaque scene pass draws what the prepass drew, at the same depth (`depth_equal`).
    let mut constants = inputs.constants.to_vec();
    if !prepass {
        constants.push(("SCENE_ALPHA_TEST", f64::from(u8::from(blend))));
    }
    let compilation = wgpu::PipelineCompilationOptions {
        constants: &constants,
        ..Default::default()
    };
    let buffers = [
        Some(Vertex::layout()),
        Some(MeshInstance::layout_with_motion()),
    ];
    let double = variant & PIPE_DOUBLE != 0;
    let mirror = variant & PIPE_MIRROR != 0;
    let main_targets = [Some(wgpu::ColorTargetState {
        format: inputs.hdr,
        // Premultiplied: a blended surface's reflections keep their strength (`fs_main`).
        blend: blend.then_some(wgpu::BlendState::PREMULTIPLIED_ALPHA_BLENDING),
        write_mask: wgpu::ColorWrites::ALL,
    })];
    let (label, vs, fs, targets): (_, _, _, &[Option<wgpu::ColorTargetState>]) = if prepass {
        (
            "mesh prepass",
            "vs_prepass",
            "fs_prepass",
            &inputs.prepass_targets,
        )
    } else {
        ("mesh", "vs_main", "fs_main", &main_targets)
    };
    inputs
        .device
        .create_render_pipeline(&wgpu::RenderPipelineDescriptor {
            label: Some(label),
            layout: Some(&inputs.layout),
            vertex: wgpu::VertexState {
                module: &inputs.shader,
                entry_point: Some(vs),
                compilation_options: compilation.clone(),
                buffers: &buffers,
            },
            primitive: wgpu::PrimitiveState {
                cull_mode: if double { None } else { Some(wgpu::Face::Back) },
                front_face: if mirror {
                    wgpu::FrontFace::Cw
                } else {
                    wgpu::FrontFace::Ccw
                },
                ..Default::default()
            },
            depth_stencil: Some(if prepass {
                inputs.depth[1].clone()
            } else if blend {
                inputs.depth[0].clone()
            } else {
                inputs.depth_equal.clone()
            }),
            multisample: Default::default(),
            fragment: Some(wgpu::FragmentState {
                module: &inputs.shader,
                entry_point: Some(fs),
                compilation_options: compilation,
                targets,
            }),
            multiview_mask: None,
            cache: None,
        })
}

/// The alpha-tested shadow pipeline (masked casters).
fn build_shadow_masked_pipeline(inputs: &ShadowPipelineInputs) -> wgpu::RenderPipeline {
    let compilation = wgpu::PipelineCompilationOptions {
        constants: &inputs.constants,
        ..Default::default()
    };
    let buffers = [
        Some(Vertex::layout()),
        Some(MeshInstance::layout_with_motion()),
    ];
    inputs
        .device
        .create_render_pipeline(&wgpu::RenderPipelineDescriptor {
            label: Some("mesh shadow masked"),
            layout: Some(&inputs.layout),
            vertex: wgpu::VertexState {
                module: &inputs.shader,
                entry_point: Some("vs_shadow_masked"),
                compilation_options: compilation.clone(),
                buffers: &buffers,
            },
            primitive: wgpu::PrimitiveState {
                cull_mode: None,
                unclipped_depth: inputs.unclipped,
                ..Default::default()
            },
            depth_stencil: Some(inputs.depth.clone()),
            multisample: Default::default(),
            fragment: Some(wgpu::FragmentState {
                module: &inputs.shader,
                entry_point: Some("fs_shadow_masked"),
                compilation_options: compilation,
                targets: &[],
            }),
            multiview_mask: None,
            cache: None,
        })
}

fn texture_layout_entry(binding: u32) -> wgpu::BindGroupLayoutEntry {
    wgpu::BindGroupLayoutEntry {
        binding,
        visibility: wgpu::ShaderStages::FRAGMENT,
        ty: wgpu::BindingType::Texture {
            sample_type: wgpu::TextureSampleType::Float { filterable: true },
            view_dimension: wgpu::TextureViewDimension::D2,
            multisampled: false,
        },
        count: None,
    }
}

/// Where a frame's materials get their textures.
#[derive(Clone, Copy)]
struct TextureSources<'a> {
    images: Option<&'a Assets<Image>>,
    registry: Option<&'a VirtualTextures>,
    settings: &'a RenderSettings,
}

/// First binding of the virtual texture bindings in group 2.
const VT_FIRST_BINDING: u32 = TEXTURE_SLOTS as u32 + 1;

fn create_texture_group(
    device: &wgpu::Device,
    layout: &wgpu::BindGroupLayout,
    sampler: &wgpu::Sampler,
    views: [&wgpu::TextureView; TEXTURE_SLOTS],
    vt: &VirtualTextureSystem,
) -> wgpu::BindGroup {
    let mut entries: Vec<wgpu::BindGroupEntry> = views
        .iter()
        .enumerate()
        .map(|(i, view)| wgpu::BindGroupEntry {
            binding: i as u32,
            resource: wgpu::BindingResource::TextureView(view),
        })
        .collect();
    entries.push(wgpu::BindGroupEntry {
        binding: TEXTURE_SLOTS as u32,
        resource: wgpu::BindingResource::Sampler(sampler),
    });
    entries.extend(vt.bind_entries(VT_FIRST_BINDING));
    device.create_bind_group(&wgpu::BindGroupDescriptor {
        label: Some("mesh textures"),
        layout,
        entries: &entries,
    })
}

impl RenderFeature for MeshFeature {
    fn name(&self) -> &str {
        "meshes"
    }

    fn init(&mut self, gpu: &GpuShared) {
        let device = &gpu.device;
        let material_layout = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: Some("mesh materials"),
            entries: &[wgpu::BindGroupLayoutEntry {
                binding: 0,
                visibility: wgpu::ShaderStages::VERTEX_FRAGMENT,
                ty: wgpu::BindingType::Buffer {
                    ty: wgpu::BufferBindingType::Storage { read_only: true },
                    has_dynamic_offset: false,
                    min_binding_size: None,
                },
                count: None,
            }],
        });
        let mut texture_entries: Vec<wgpu::BindGroupLayoutEntry> = (0..TEXTURE_SLOTS as u32)
            .map(texture_layout_entry)
            .collect();
        texture_entries.push(wgpu::BindGroupLayoutEntry {
            binding: TEXTURE_SLOTS as u32,
            visibility: wgpu::ShaderStages::FRAGMENT,
            ty: wgpu::BindingType::Sampler(wgpu::SamplerBindingType::Filtering),
            count: None,
        });
        let feedback_writes = feedback_writes(gpu);
        texture_entries.extend(VirtualTextureSystem::layout_entries(
            VT_FIRST_BINDING,
            feedback_writes,
        ));
        let texture_layout = device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {
            label: Some("mesh textures"),
            entries: &texture_entries,
        });
        // Trilinear, repeating, 16x anisotropic where supported (wgpu clamps to 1 otherwise).
        let sampler = device.create_sampler(&wgpu::SamplerDescriptor {
            label: Some("material sampler"),
            address_mode_u: wgpu::AddressMode::Repeat,
            address_mode_v: wgpu::AddressMode::Repeat,
            address_mode_w: wgpu::AddressMode::Repeat,
            mag_filter: wgpu::FilterMode::Linear,
            min_filter: wgpu::FilterMode::Linear,
            mipmap_filter: wgpu::MipmapFilterMode::Linear,
            anisotropy_clamp: 16,
            ..Default::default()
        });
        self.default_textures = DEFAULT_TEXELS
            .iter()
            .enumerate()
            .map(|(slot, texel)| {
                let image = Image::solid(*texel, COLOR_SLOT[slot]);
                upload_image(gpu, &image, COLOR_SLOT[slot], false).expect("1x1 default texture")
            })
            .collect();

        let shader = gpu.shader("mesh", &mesh_source(feedback_writes), true);
        let pipeline_layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
            label: Some("mesh"),
            bind_group_layouts: &[
                Some(&gpu.frame_layout),
                Some(&material_layout),
                Some(&texture_layout),
            ],
            immediate_size: 0,
        });
        let buffers = [
            Some(Vertex::layout()),
            Some(MeshInstance::layout_with_motion()),
        ];
        let shadow_shader = gpu.shader("mesh shadow", &mesh_shadow_source(feedback_writes), false);
        let shadow_primitive = wgpu::PrimitiveState {
            cull_mode: None,
            unclipped_depth: gpu.features.contains(wgpu::Features::DEPTH_CLIP_CONTROL),
            ..Default::default()
        };
        let shadow_layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
            label: Some("mesh shadow"),
            bind_group_layouts: &[Some(&gpu.shadow_view_layout), Some(&material_layout)],
            immediate_size: 0,
        });
        self.shadow_pipeline = Some(device.create_render_pipeline(
            &wgpu::RenderPipelineDescriptor {
                label: Some("mesh shadow"),
                layout: Some(&shadow_layout),
                vertex: wgpu::VertexState {
                    module: &shadow_shader,
                    entry_point: Some("vs_shadow"),
                    compilation_options: Default::default(),
                    buffers: &buffers,
                },
                primitive: shadow_primitive,
                depth_stencil: Some(gpu.shadow_depth_state()),
                multisample: Default::default(),
                fragment: None,
                multiview_mask: None,
                cache: None,
            },
        ));
        let shadow_masked_layout = device.create_pipeline_layout(&wgpu::PipelineLayoutDescriptor {
            label: Some("mesh shadow masked"),
            bind_group_layouts: &[
                Some(&gpu.shadow_view_layout),
                Some(&material_layout),
                Some(&texture_layout),
            ],
            immediate_size: 0,
        });
        self.materials = Some(GrowBuffer::new(
            device,
            "mesh materials",
            wgpu::BufferUsages::STORAGE,
            64 * std::mem::size_of::<GpuMaterial>() as u64,
        ));
        self.instances = Some(GrowBuffer::new(
            device,
            "mesh instances",
            wgpu::BufferUsages::VERTEX,
            1024 * std::mem::size_of::<MeshInstance>() as u64,
        ));

        self.shader_features = ShaderFeatures::default();
        self.shader = Some(shader);
        self.pipeline_layout = Some(pipeline_layout);
        self.shadow_shader = Some(shadow_shader);
        self.shadow_masked_layout = Some(shadow_masked_layout);
        self.clear_pipelines();
        self.clusters = Some(ClusterRenderer::new(
            gpu,
            &material_layout,
            &texture_layout,
            self.shader_features,
        ));
        self.impostors = Some(Impostors::new(
            gpu,
            &mesh_source(feedback_writes),
            &material_layout,
            &texture_layout,
        ));
        self.material_layout = Some(material_layout);
        self.texture_layout = Some(texture_layout);
        self.sampler = Some(sampler);
        self.material_group = None;
        self.vt = Some(VirtualTextureSystem::new(gpu));
        // Texture set 0: the shared default set for untextured materials.
        self.texture_sets.clear();
        self.texture_set_ids.clear();
        self.free_set_ids.clear();
        self.build_default_set(device);
    }

    fn prepare(
        &mut self,
        world: &mut World,
        gpu: &GpuShared,
        view: &ViewData,
        settings: &RenderSettings,
    ) {
        if self.shader.is_none() {
            return;
        }
        self.frame += 1;
        let mut steps = PrepareSteps::default();
        steps.step("meshes: begin frame");
        if let Some(clusters) = &mut self.clusters {
            clusters.begin_frame(gpu);
        }
        // Virtual textures: feedback in, tiles loaded and uploaded, tables written. Texture
        // sets are rebuilt when the cache's bindings changed.
        if let Some(vt) = &mut self.vt {
            vt.begin_frame(gpu, settings);
            let generation = vt.bind_generation();
            if let Some(stats) = world.get_resource_mut::<VirtualTextureStats>() {
                stats.into_inner().clone_from(vt.stats());
            }
            if self
                .texture_sets
                .first()
                .and_then(Option::as_ref)
                .is_some_and(|s| s.vt_generation != generation)
            {
                self.build_default_set(&gpu.device);
            }
        }
        steps.step("meshes: sync");
        self.clustered.clear();
        let frame = self.frame;
        let mut scene = std::mem::take(&mut self.scene);
        scene.sync(world, frame);
        self.shadow_changes.extend_from_slice(&scene.changes);
        if !view.extra_view {
            self.check_static_images(view);
        }
        let mut skin_query = self.skin_query.take().unwrap_or_else(|| world.query());
        let world_ref: &World = world;
        let Some(mesh_assets) = world_ref.get_resource::<Assets<Mesh>>() else {
            self.scene = scene;
            self.skin_query = Some(skin_query);
            return;
        };
        if mesh_assets.removals() != self.mesh_removals {
            self.mesh_removals = mesh_assets.removals();
            self.forget_removed_meshes(mesh_assets);
        }
        let material_assets = world_ref.get_resource::<Assets<StandardMaterial>>();
        let sources = TextureSources {
            images: world_ref.get_resource::<Assets<Image>>(),
            registry: world_ref.get_resource::<VirtualTextures>(),
            settings,
        };
        let image_assets = sources.images;
        let preset_size = settings.material_texture_size;
        let default_material = StandardMaterial::default();

        self.items.clear();
        self.material_data.clear();
        self.material_index.clear();
        let mut culled = 0u32;
        let shadows = view.sun_shadows || view.sky_occlusion.enabled;
        let lod_pixels = settings.mesh_lod_pixels.max(0.0);
        if let Some(meshes) = world.get_resource::<Assets<Mesh>>() {
            self.collect_lods(&gpu.queue, meshes);
        }

        // This view's camera position last frame (each view has its own).
        let prev_origin = view.prev_origin;
        // The disk cache of cluster builds.
        let cache_settings = (
            settings.virtual_geometry_cache,
            settings.virtual_geometry_cache_dir.clone(),
            settings.virtual_geometry_cache_mb,
        );
        if self.cache_settings.as_ref() != Some(&cache_settings) {
            let cache = cache_settings
                .0
                .then(|| {
                    if cache_settings.1.is_empty() {
                        crate::virtual_geometry::default_cache_dir()
                    } else {
                        Some(cache_settings.1.clone().into())
                    }
                })
                .flatten()
                .map(|dir: std::path::PathBuf| {
                    BuildCache::new(dir, cache_settings.2 as u64 * 1024 * 1024)
                });
            if let Some(clusters) = &mut self.clusters {
                clusters.set_cache(cache);
            }
            self.cache_settings = Some(cache_settings);
        }

        steps.step("meshes: skins");
        // Skinned meshes: changed poses' bones written, bounds posed (before the tables below
        // take the bounds).
        for (skin, resolved) in skin_query.iter(world_ref) {
            let handle = mesh_assets.canonical(resolved.mesh);
            let Some(asset) = mesh_assets.get(handle) else {
                continue;
            };
            if let Some((center, half)) =
                self.skins.prepare(gpu, handle.index(), asset, skin, frame)
                && let Some(g) = self.meshes.get_mut(&handle.index())
            {
                g.center = center;
                g.half_extents = half;
                g.min_y = center.y - half.y;
                g.height = (2.0 * half.y).max(1e-3);
            }
        }
        self.skin_query = Some(skin_query);
        self.skins.evict(frame, SKIN_EVICT_FRAMES);

        steps.step("meshes: gather");
        // This frame's tables of the meshes and materials the scene uses.
        let min_triangles = (settings.virtual_geometry_min_triangles as usize).max(1);
        for raw in scene.meshes_used() {
            // Key GPU caches by the slot that holds the value, so aliases share uploads.
            let handle = mesh_assets.canonical(Handle::from_index(raw));
            let version = mesh_assets.version(handle);
            let triangles = mesh_assets.get(handle).map(|m| m.indices.len() / 3);
            let mut entry = MeshFrame {
                index: handle.index(),
                version,
                exists: triangles.is_some(),
                dense: triangles.is_some_and(|t| t >= min_triangles),
                small: triangles.unwrap_or(0) < SMALL_BUILD_TRIANGLES,
                ..Default::default()
            };
            if let Some(gpu_mesh) = self.meshes.get(&handle.index())
                && gpu_mesh.version == version
            {
                entry.set_uploaded(
                    gpu_mesh,
                    self.lod_jobs.contains_key(&handle.index()),
                    self.skins.skins.contains_key(&handle.index()),
                );
            }
            let i = raw as usize;
            if i >= self.mesh_frames.len() {
                self.mesh_frames.resize(i + 1, MeshFrame::default());
            }
            self.mesh_frames[i] = entry;
        }
        for raw in scene.materials_used() {
            let handle = Handle::from_index(raw);
            let handle = material_assets.map_or(handle, |m| m.canonical(handle));
            let loaded = material_assets.and_then(|m| m.get(handle));
            let material = loaded.unwrap_or(&default_material);
            let impostor_key = loaded.map(|m| {
                use std::hash::{Hash, Hasher};
                let mut h = std::collections::hash_map::DefaultHasher::new();
                // What it looks like, not its version: a material written to every frame
                // with the same values keeps its impostors.
                bytemuck::bytes_of(&m.to_gpu()).hash(&mut h);
                for image in m.textures().into_iter().flatten() {
                    image.index().hash(&mut h);
                    image_assets.map(|a| a.version(image)).hash(&mut h);
                }
                (h.finish() << 32) | handle.index() as u64
            });
            let i = raw as usize;
            if i >= self.material_frames.len() {
                self.material_frames.resize(i + 1, MaterialFrame::default());
            }
            self.material_frames[i] = MaterialFrame {
                index: handle.index(),
                blend: material.alpha_mode == AlphaMode::Blend,
                masked: matches!(material.alpha_mode, AlphaMode::Mask(_)),
                double_sided: material.double_sided,
                glows: material.emissive_strength > 0.0
                    && material.emissive.iter().any(|&c| c > 0.0),
                still_opaque: material.alpha_mode == AlphaMode::Opaque && material.wind_sway <= 0.0,
                sways: material.wind_sway > 0.0,
                slot: None,
                impostor_key,
            };
        }

        steps.step("meshes: classify");
        // 1. Which slots the serial pass looks at first: cluster candidates and meshes not
        //    uploaded yet (a quick parallel scan; the cull comes after the serial pass).
        let clusters_on = settings.virtual_geometry && self.clusters.is_some();
        let threads = gather_threads(scene.hot.len());
        let mut chunks = std::mem::take(&mut self.gather_scratch);
        chunks.resize_with(threads, Default::default);
        for out in &mut chunks {
            out.deferred.clear();
        }
        {
            let (mesh_frames, material_frames) = (&self.mesh_frames, &self.material_frames);
            let classify = |base: usize, hot: &[Hot], out: &mut GatherChunk| {
                for (k, h) in hot.iter().enumerate() {
                    if h.flags & mesh_scene::VISIBLE == 0 {
                        continue;
                    }
                    let mesh = &mesh_frames[h.mesh as usize];
                    if mesh.version == 0 {
                        continue;
                    }
                    let mat = &material_frames[h.material as usize];
                    if !mesh.ready || (clusters_on && cluster_candidate(h, mesh, mat)) {
                        out.deferred.push((base + k) as u32);
                    }
                }
            };
            let per = scene.hot.len().div_ceil(threads).max(1);
            let classify = &classify;
            run_jobs(
                scene
                    .hot
                    .chunks(per)
                    .zip(chunks.iter_mut())
                    .enumerate()
                    .map(|(k, (hot, out))| move || classify(k * per, hot, out)),
            );
        }
        let mut deferred = std::mem::take(&mut self.deferred);
        deferred.clear();
        for chunk in &chunks {
            deferred.extend_from_slice(&chunk.deferred);
        }
        self.gather_scratch = chunks;
        self.cluster_slots.clear();
        self.cluster_slots.resize(scene.hot.len().div_ceil(64), 0);

        steps.step("meshes: clusters");
        // 2. In turn: the cluster path (dense opaque meshes and displaced ones, culled and
        //    picked on the GPU once built; until then drawn as instances) and first uploads.
        for &slot in &deferred {
            let s = slot as usize;
            let hot = scene.hot[s];
            let raw = hot.mesh as usize;
            let mat = self.material_frames[hot.material as usize];
            let mesh = self.mesh_frames[raw];
            if clusters_on && cluster_candidate(&hot, &mesh, &mat) {
                let cold = &scene.cold[s];
                let mesh_handle = Handle::<Mesh>::from_index(mesh.index);
                let material = material_assets
                    .and_then(|m| m.get(Handle::from_index(mat.index)))
                    .unwrap_or(&default_material);
                let displacement = if hot.flags & mesh_scene::DISPLACED != 0 {
                    world_ref.get::<Displacement>(cold.entity)
                } else {
                    None
                };
                let cluster_path = match displacement {
                    None => Some((mesh.index as u64, None)),
                    Some(d) => match height_source(d, material, image_assets, preset_size) {
                        Some(source) => {
                            let key = displaced_key(mesh.index, d, material, &source);
                            Some((key, Some((d, source))))
                        }
                        None => {
                            if self.warned_no_height.insert(mesh.index) {
                                tracing::warn!(
                                    "a Displacement takes its height from the material, which \
                                     has no height_texture or preset (or its pixels were \
                                     released): drawing mesh {} without displacement",
                                    mesh.index
                                );
                            }
                            None
                        }
                    },
                };
                let small = match &cluster_path {
                    Some((_, Some((d, _)))) => (d.max_triangles as usize) < SMALL_BUILD_TRIANGLES,
                    _ => mesh.small,
                };
                // Undisplaced meshes ask once a frame.
                let shared = matches!(cluster_path, Some((_, None)));
                let ready = match mesh.clusters.filter(|_| shared) {
                    Some(ready) => ready,
                    None => {
                        let preset_heights = &mut self.preset_heights;
                        let ready = match (&cluster_path, &mut self.clusters) {
                            (Some((cluster_key, displaced)), Some(clusters)) => {
                                clusters.ready(*cluster_key, mesh.version, small, || {
                                    let mesh = mesh_assets.get(mesh_handle)?.clone();
                                    let displacement = match displaced {
                                        None => None,
                                        Some((d, source)) => Some(resolve_displacement(
                                            d,
                                            material,
                                            source,
                                            image_assets,
                                            preset_heights,
                                            gpu,
                                        )?),
                                    };
                                    Some(BuildJob { mesh, displacement })
                                })
                            }
                            _ => false,
                        };
                        if shared {
                            self.mesh_frames[raw].clusters = Some(ready);
                        }
                        ready
                    }
                };
                if ready && let Some((cluster_key, _)) = cluster_path {
                    // Drawn (or culled) here: the instanced cull leaves it out.
                    set_bit(&mut self.cluster_slots, slot);
                    self.clustered.insert(mesh.index);
                    if hot.max_distance < f32::MAX
                        && let Some(bounds) =
                            self.clusters.as_ref().and_then(|c| c.bounds(cluster_key))
                    {
                        let center = (cold.transform.transform_point(bounds.center.as_dvec3())
                            - view.origin)
                            .as_vec3();
                        if center.length() - bounds.radius * hot.scale > hot.max_distance {
                            culled += 1;
                            continue;
                        }
                    }
                    // Displaced: the relief is geometry now, so parallax is off and the normal
                    // map only adds what is finer than the triangles.
                    let (material_slot, textures) = match displacement {
                        Some(d) => {
                            let strength = d.normal_map_strength.clamp(0.0, 1.0);
                            self.material_slot(
                                gpu,
                                mat.index as u64 | (strength.to_bits() as u64) << 32 | 1 << 63,
                                &d.adjust_material(material),
                                &sources,
                            )
                        }
                        None => self.material_slot(gpu, mat.index as u64, material, &sources),
                    };
                    if let Some(clusters) = &mut self.clusters {
                        clusters.push_instance(ClusterInstance {
                            mesh: cluster_key,
                            model: cold.transform.matrix_relative_to(view.origin),
                            prev_model: cold.previous_at(frame).matrix_relative_to(prev_origin),
                            material: material_slot,
                            textures,
                            double_sided: material.double_sided,
                            casts_shadows: shadows && hot.flags & mesh_scene::CASTS != 0,
                        });
                    }
                    continue;
                }
            }

            // The instanced path: uploaded (and its levels asked for) the first time this
            // frame; the cull takes it once uploaded.
            if !self.mesh_frames[raw].checked {
                let handle = Handle::<Mesh>::from_index(mesh.index);
                let resident = self.meshes.get(&mesh.index).map(|m| m.version);
                if resident != Some(mesh.version)
                    && let Some(asset) = mesh_assets.get(handle)
                    // Within this frame's upload budget (asked once per mesh a frame), else
                    // drawn from a later frame; an edit of a resident mesh goes at once.
                    && gpu.uploads.take(
                        MESH_UPLOAD_KEY | mesh.index as u64,
                        (std::mem::size_of_val(asset.vertices.as_slice())
                            + std::mem::size_of_val(asset.indices.as_slice()))
                            as u64,
                        resident.is_some(),
                    )
                {
                    self.uploads += 1;
                    self.edits += resident.is_some() as u32;
                    self.upload_mesh(gpu, mesh.index, asset, mesh.version);
                    // Skinned meshes are drawn whole (`GpuSkin` requires `NoMeshLod`).
                    if lod_pixels > 0.0 && !self.skins.skins.contains_key(&mesh.index) {
                        self.request_lods(mesh.index, handle, asset, mesh.version);
                    }
                }
                let building = self.lod_jobs.contains_key(&mesh.index);
                let skinned = self.skins.skins.contains_key(&mesh.index);
                let entry = &mut self.mesh_frames[raw];
                entry.checked = true;
                if let Some(gpu_mesh) = self.meshes.get(&mesh.index) {
                    entry.set_uploaded(gpu_mesh, building, skinned);
                }
            }
        }
        self.deferred = deferred;

        // 3. Material slots (and texture sets) for the materials drawn lately; the cull's
        //    items take theirs from these.
        steps.step("meshes: materials");
        let recent = frame.saturating_sub(MATERIAL_KEEP_FRAMES);
        for raw in scene.materials_used() {
            let i = raw as usize;
            if self.material_frames[i].slot.is_none()
                && self
                    .material_seen
                    .get(i)
                    .is_some_and(|&seen| seen >= recent)
            {
                let handle = Handle::from_index(self.material_frames[i].index);
                let material = material_assets
                    .and_then(|m| m.get(handle))
                    .unwrap_or(&default_material);
                let slot = self.material_slot(gpu, handle.index() as u64, material, &sources);
                self.material_frames[i].slot = Some(slot);
            }
        }
        self.scene = scene;

        // 4. The cull of the instanced path: on the render thread (`prepare_frame`) for the
        //    camera's view, here for extra views and after a camera cut (when every material
        //    must be at hand at once).
        self.cull_later = !view.extra_view && view.history_valid;
        if !self.cull_later {
            steps.step("meshes: cull");
            culled += self.cull(view, settings);
            culled += self.finish_items(gpu, Some((material_assets, &sources, &default_material)));
        }
        // Meshes now drawn only as clusters don't need their instanced copy.
        if !self.clustered.is_empty() {
            let clustered = &self.clustered;
            let pool = &mut self.pool;
            self.meshes.retain(|m, g| {
                // Used last frame or this one (the cull may run on the render thread).
                let keep = g.last_used + 1 >= frame || !clustered.contains(m);
                if !keep {
                    g.free(pool);
                }
                keep
            });
        }
        if let Some(clusters) = &mut self.clusters {
            clusters.end_prepare(gpu, view, settings);
        }
        // The rest reads no world: `prepare_frame`, on the render thread when pipelined.
        self.culled = culled;
        self.loading = world.contains_resource::<engine_world::LoadingBudget>();
        self.headless = world
            .get_resource::<EngineConfig>()
            .is_none_or(|c| c.headless);
        self.prepared = true;
        let mut diagnostics = world.get_resource_mut::<Diagnostics>();
        steps.publish(diagnostics.as_deref_mut(), gpu);
    }

    fn prepare_frame(
        &mut self,
        gpu: &GpuShared,
        view: &ViewData,
        settings: &RenderSettings,
        diagnostics: &mut Diagnostics,
    ) {
        if !std::mem::take(&mut self.prepared) {
            return;
        }
        let mut steps = PrepareSteps::default();
        if std::mem::take(&mut self.cull_later) {
            // The cull `prepare` left for the render thread: the main thread only synced.
            steps.step("meshes: cull");
            self.culled += self.cull(view, settings);
            self.culled += self.finish_items(gpu, None);
        }
        let frame = self.frame;
        let culled = self.culled;
        let shadows = view.sun_shadows || view.sky_occlusion.enabled;
        let prev_origin = view.prev_origin;
        let lod_pixels = settings.mesh_lod_pixels.max(0.0);
        let min_pixels = settings.min_object_pixels.max(0.0);
        let impostor_pixels = settings.impostor_pixels.max(0.0);
        let threads = gather_threads(self.scene.hot.len());
        steps.step("meshes: sort and batch");
        // Order: opaque (by pipeline, texture set, mesh), transparent (back to front). The
        // visible items' keys are sorted, not the items themselves.
        self.order.clear();
        self.order.extend(
            self.items
                .iter()
                .enumerate()
                .filter(|(_, i)| i.visible)
                .map(|(n, i)| (Item::sort_key(i), n as u32)),
        );
        self.order.sort_unstable_by_key(|&(key, _)| key);

        self.layout.clear();
        self.opaque.clear();
        self.transparent.clear();
        for s in self.shadow.iter_mut().chain(&mut self.shadow_static) {
            s.clear();
        }
        self.keys.clear();

        // Opaque.
        let items = &self.items;
        let ordered = || self.order.iter().map(|&(_, n)| (n, &items[n as usize]));
        for (n, item) in
            ordered().filter(|(_, i)| i.pipeline & PIPE_BLEND == 0 && i.lod != IMPOSTOR_LOD)
        {
            self.layout.push(n);
            self.keys.push(BatchKey {
                pipeline: item.pipeline,
                textures: item.textures,
                mesh: item.mesh,
                lod: item.lod,
            });
        }
        // Old levels while new ones fade in, after the rest in the same order (the sort key
        // ends with the level), so they batch together and split no runs.
        let mut fading: Vec<(u64, u32)> = ordered()
            .filter(|(_, i)| {
                i.pipeline & PIPE_BLEND == 0 && i.lod != IMPOSTOR_LOD && i.lod_fade > 0.0
            })
            .map(|(n, i)| {
                let key = Item {
                    lod: i.lod_from,
                    ..*i
                };
                (key.sort_key(), n)
            })
            .collect();
        fading.sort_unstable_by_key(|&(key, _)| key);
        for &(_, n) in &fading {
            let item = &items[n as usize];
            self.layout.push(n | AS_OLD_LEVEL);
            self.keys.push(BatchKey {
                pipeline: item.pipeline,
                textures: item.textures,
                mesh: item.mesh,
                lod: item.lod_from,
            });
        }
        self.lods_fading = fading.len() as u32;
        Self::batch(&self.keys, 0, &mut self.opaque);
        // Impostors: one draw for all of them.
        let first = self.layout.len();
        self.layout.extend(
            ordered()
                .filter(|(_, i)| i.lod == IMPOSTOR_LOD || i.fade > 0.0)
                .map(|(n, _)| n | AS_IMPOSTOR),
        );
        self.impostor_view = (first as u32, (self.layout.len() - first) as u32);
        self.impostors_fading = ordered().filter(|(_, i)| i.fade > 0.0).count() as u32;
        self.impostor_shadow = Default::default();
        self.impostor_shadow_static = Default::default();
        // Transparent.
        let first = self.layout.len();
        self.keys.clear();
        for (n, item) in ordered().filter(|(_, i)| i.pipeline & PIPE_BLEND != 0) {
            self.layout.push(n);
            self.keys.push(BatchKey {
                pipeline: item.pipeline,
                textures: item.textures,
                mesh: item.mesh,
                lod: item.lod,
            });
        }
        Self::batch(&self.keys, first as u32, &mut self.transparent);
        steps.step("meshes: shadow lists");
        // Shadows: opaque casters batch by mesh (depth only); masked casters by texture set
        // and mesh (alpha tested). Each map draws casters at the level of detail its texels
        // can show, and leaves out those smaller than a texel. Casters still since a map's
        // static image was drawn are in it; the others are drawn every frame on top. A static
        // image drawn again this frame takes every still caster in its square.
        if shadows {
            let shadow_key = |item: &Item, lod: u8| BatchKey {
                pipeline: if item.masked {
                    SHADOW_MASKED
                } else {
                    SHADOW_DEPTH
                },
                textures: if item.masked { item.textures } else { 0 },
                mesh: item.mesh,
                lod,
            };
            // By mesh, then scale: a map's level grows with scale, so each mesh's levels stay
            // together in its batches. (Keys sorted, not items; `order` is free again.)
            self.order.clear();
            self.order
                .extend(
                    self.items
                        .iter()
                        .enumerate()
                        .filter(|(_, i)| i.casts)
                        .map(|(n, item)| {
                            let k = shadow_key(item, 0);
                            // Scale to 19 bits (positive: exponent and 11 bits of
                            // mantissa), enough to keep each mesh's levels together; the
                            // pool page before the mesh, for longer multi-draw runs.
                            let key = (k.pipeline as u64) << 63
                                | (k.textures as u64 & 0x3_ffff) << 45
                                | (item.page as u64 & 0x3f) << 39
                                | (k.mesh as u64 & 0xf_ffff) << 19
                                | (item.scale.to_bits() >> 12) as u64 & 0x7_ffff;
                            (key, n as u32)
                        }),
                );
            self.order.sort_unstable_by_key(|&(key, _)| key);
            self.casters.clear();
            self.casters.extend(self.order.iter().map(|&(_, n)| n));
            let cascades = if view.sun_shadows {
                (view.cascades.count as usize).min(MAX_CASCADES)
            } else {
                0
            };
            let maps = (0..cascades)
                .chain(view.sky_occlusion.enabled.then_some(SKY_OCCLUSION_VIEW))
                .chain((view.sun_shadows && view.far_shadow.enabled).then_some(FAR_SHADOW_MAP));
            // Each map's casters on its own thread, then their instances in map order.
            let maps: Vec<usize> = maps.collect();
            let mut lists = std::mem::take(&mut self.shadow_scratch);
            lists.resize_with(maps.len(), Default::default);
            let (items, casters, meshes) = (&self.items, &self.casters, &self.meshes);
            let image_frame = self.image_frame;
            let fill = |c: usize, out: &mut MapCasters| {
                out.clear();
                let texel = match c {
                    SKY_OCCLUSION_VIEW => {
                        view.sky_occlusion.extent / view.sky_occlusion.map_size.max(1) as f32
                    }
                    FAR_SHADOW_MAP => view.far_shadow.texel(),
                    _ => 2.0 * view.cascades.half_extent[c] / view.cascades.map_size.max(1) as f32,
                };
                let redraw = static_redraw(view, c);
                // Casters still since this frame are in the image when it is drawn again.
                let image = if redraw { frame } else { image_frame[c] };
                for &n in casters {
                    let item = &items[n as usize];
                    // Swaying leaves move in the near cascades' shadows: never still there.
                    let can_rest = !(item.sways && c < 2);
                    let in_image = can_rest && item.since <= image;
                    if in_image && !redraw {
                        continue;
                    }
                    let inside = if in_image {
                        map_holds(view, c, item.center, item.radius)
                    } else {
                        map_shades(view, c, item.center, item.radius)
                    };
                    if !inside || 2.0 * item.radius < min_pixels * texel {
                        continue;
                    }
                    if !in_image && can_rest && item.since <= frame {
                        out.waiting += 1;
                        out.oldest = out.oldest.min(item.since);
                    }
                    // Past the cascades only big casters are drawn every frame; mid-size ones
                    // cast once still, from the static image.
                    if !in_image
                        && c == FAR_SHADOW_MAP
                        && item.radius < FAR_MOVING_CASTER_TEXELS * texel
                    {
                        continue;
                    }
                    let list = if in_image {
                        &mut out.still
                    } else {
                        &mut out.moving
                    };
                    if item.impostor != crate::impostor::NONE
                        && 2.0 * item.radius < impostor_pixels * texel
                    {
                        list.impostors.push(n);
                        continue;
                    }
                    let lod = match meshes.get(&item.mesh) {
                        Some(m) if lod_pixels > 0.0 && !item.full_detail => {
                            crate::mesh_lod::pick(m.errors(), item.scale, lod_pixels * texel)
                        }
                        _ => 0,
                    };
                    list.picked.push(n);
                    list.keys.push(shadow_key(item, lod));
                }
            };
            let fill = &fill;
            let jobs = maps.iter().zip(lists.iter_mut());
            if casters.len() >= PARALLEL_CASTERS {
                run_jobs(jobs.map(|(&c, list)| move || fill(c, list)));
            } else {
                jobs.for_each(|(&c, list)| fill(c, list));
            }
            let mut join = None;
            for (&c, lists) in maps.iter().zip(&lists) {
                for (list, still) in [(&lists.moving, false), (&lists.still, true)] {
                    let first = self.layout.len();
                    self.layout.extend_from_slice(&list.picked);
                    let out = if still {
                        &mut self.shadow_static[c]
                    } else {
                        &mut self.shadow[c]
                    };
                    Self::batch(&list.keys, first as u32, out);
                    let first = self.layout.len();
                    self.layout
                        .extend(list.impostors.iter().map(|&n| n | AS_IMPOSTOR));
                    let range = (first as u32, list.impostors.len() as u32);
                    if still {
                        self.impostor_shadow_static[c] = range;
                    } else {
                        self.impostor_shadow[c] = range;
                    }
                }
                if view.extra_view {
                    continue;
                }
                if static_redraw(view, c) {
                    // The image now holds what was still this frame.
                    self.image_frame[c] = frame;
                    self.static_dirty[c] = false;
                    self.static_waiting[c] = false;
                    self.static_triangles[c] = self.shadow_static[c]
                        .iter()
                        .map(|b| {
                            meshes
                                .get(&b.key.mesh)
                                .map_or(0, |m| m.level(b.key.lod).1 / 3)
                                as u64
                                * b.count as u64
                        })
                        .sum();
                }
                // Still casters waiting to join: one map a frame asks for its image again.
                let due = lists.waiting >= JOIN_COUNT
                    || (lists.waiting > 0 && lists.oldest + JOIN_FRAMES <= frame);
                self.static_waiting[c] = false;
                if due && join.is_none() {
                    join = Some(c);
                }
            }
            if let Some(c) = join {
                self.static_waiting[c] = true;
            }
            self.shadow_scratch = lists;
        }

        // This frame's impostor bake (recorded in `compute`).
        let meshes = &self.meshes;
        if let Some(impostors) = &mut self.impostors {
            // BC7 where material images are compressed (decided with the first bake).
            let compress = settings.texture_compression != TextureCompression::Off
                && gpu
                    .features
                    .contains(wgpu::Features::TEXTURE_COMPRESSION_BC)
                && gpu.adapter_info.backend != wgpu::Backend::Gl
                && (gpu.adapter_info.device_type != wgpu::DeviceType::Cpu
                    || settings.texture_compression_on_cpu);
            let budget = (settings.impostor_atlas_layers, compress, self.loading);
            impostors.schedule(gpu, budget, |m| {
                meshes.get(&m).map_or((0.0, 1.0), |g| (g.min_y, g.height))
            });
        }

        steps.step("meshes: upload");
        // The instance data in draw order, written by parallel chunks straight into the
        // upload's staging memory.
        let device = &gpu.device;
        let queue = &gpu.queue;
        if let Some(instances) = &mut self.instances {
            const SIZE: usize = std::mem::size_of::<MeshInstance>();
            let (items, scene, mesh_frames) = (&self.items, &self.scene, &self.mesh_frames);
            let instance = |n: u32| {
                let item = &items[(n & ITEM) as usize];
                let s = item.slot as usize;
                let cold = &scene.cold[s];
                let mesh = &mesh_frames[scene.hot[s].mesh as usize];
                let impostor = if n & AS_IMPOSTOR != 0 {
                    item.impostor
                } else {
                    0
                };
                // The dither rides in the normal matrix's spare lane (0: drawn whole): a
                // positive share hides the pixels whose noise is below it, a negative one keeps
                // only those below its negation (`dither_keeps` in lib_frame.wgsl). A game's
                // `DitherFade` hides `|t|` of the pixels; in a cross-fade the mesh hides the
                // `fade` share its impostor shows, and a new level shows the `lod_fade` share
                // its old level hides.
                let mut normal = cold.normal;
                normal[0][3] = if item.dither > 0.0 {
                    item.dither
                } else if item.dither < 0.0 {
                    -(1.0 + item.dither)
                } else if n & AS_IMPOSTOR != 0 {
                    -item.fade
                } else if n & AS_OLD_LEVEL != 0 {
                    item.lod_fade
                } else if item.lod_fade > 0.0 {
                    -item.lod_fade
                } else {
                    item.fade
                };
                bytemuck::cast::<MeshInstance, [u8; SIZE]>(MeshInstance {
                    m: cold.rows(view.origin),
                    n: normal,
                    extra: [
                        item.material_slot,
                        impostor,
                        mesh.min_y.to_bits(),
                        mesh.height.to_bits(),
                    ],
                    prev: cold.previous_rows(frame, prev_origin),
                })
            };
            // One staging write per chunk, each filled on its own worker.
            let layout = &self.layout;
            let per = layout.len().div_ceil(threads).max(PARALLEL_GATHER);
            instances.reserve(device, (layout.len() * SIZE) as u64);
            let buffer = &instances.buffer;
            let jobs = layout.chunks(per).enumerate().filter_map(|(k, part)| {
                let size = wgpu::BufferSize::new((part.len() * SIZE) as u64)?;
                let mut view = queue.write_buffer_with(buffer, (k * per * SIZE) as u64, size)?;
                let instance = &instance;
                Some(move || {
                    let (out, _) = view.slice(..).into_chunks::<SIZE>();
                    out.write_iter(part.iter().map(|&n| instance(n)));
                })
            });
            run_jobs(jobs.collect::<Vec<_>>().into_iter());
        }
        if self.material_data.is_empty() {
            self.material_data
                .push(StandardMaterial::default().to_gpu());
        }
        self.write_draw_args(gpu, settings);
        steps.step("meshes: pipelines");
        // Pipelines with the shader parts this frame's materials need, from now on.
        let needed = self
            .material_data
            .iter()
            .fold(self.shader_features, |f, m| {
                f.union(ShaderFeatures {
                    virtual_textures: m.flags[1] != 0 || m.flags[2] != 0,
                    anti_tiling: m.flags[0] & ANTI_TILING_FLAG != 0,
                })
            });
        if needed != self.shader_features {
            self.shader_features = needed;
            self.clear_pipelines();
            if let Some(clusters) = &mut self.clusters {
                clusters.set_shader_features(needed);
            }
        }
        self.ensure_pipelines(gpu, settings.pipeline_warmup.on(self.headless));
        steps.step("meshes: upload materials");
        let grown = self
            .materials
            .as_mut()
            .is_some_and(|m| m.write(device, queue, bytemuck::cast_slice(&self.material_data)));
        if (grown || self.material_group.is_none())
            && let (Some(layout), Some(materials)) = (&self.material_layout, &self.materials)
        {
            self.material_group = Some(device.create_bind_group(&wgpu::BindGroupDescriptor {
                label: Some("mesh materials"),
                layout,
                entries: &[wgpu::BindGroupEntry {
                    binding: 0,
                    resource: materials.buffer.as_entire_binding(),
                }],
            }));
        }
        if self.frame.is_multiple_of(120) {
            self.evict();
        }

        steps.finish();
        // Stats.
        let mut stats = FeatureStats {
            culled,
            ..Default::default()
        };
        // Draw commands (a multi-draw counts once), the prepass's not counted.
        let all = |_: u8| true;
        stats.draw_calls +=
            self.commands(&self.opaque, all) + self.commands(&self.transparent, all);
        let masked = |p: u8| p == SHADOW_MASKED;
        for list in self.shadow.iter().chain(self.shadow_static.iter()) {
            stats.draw_calls += self.commands(list, masked);
        }
        for b in self.opaque.iter().chain(self.transparent.iter()) {
            stats.instances += b.count;
            if let Some(m) = self.meshes.get(&b.key.mesh) {
                stats.triangles += (m.level(b.key.lod).1 / 3) as u64 * b.count as u64;
            }
        }
        for (_, count) in std::iter::once(self.impostor_view)
            .chain(self.impostor_shadow)
            .chain(self.impostor_shadow_static)
        {
            stats.draw_calls += (count > 0) as u32;
        }
        stats.instances += self.impostor_view.1;
        stats.triangles += 2 * self.impostor_view.1 as u64;
        if let Some(clusters) = &self.clusters {
            let c = clusters.stats();
            stats.draw_calls += c.draw_calls;
            stats.instances += c.instances;
            stats.triangles += c.triangles;
        }
        self.stats = stats;
        if engine_core::profile::enabled()
            && self
                .last_report
                .is_none_or(|t| t.elapsed().as_secs_f32() >= PROFILE_REPORT_SECS)
        {
            self.last_report = Some(std::time::Instant::now());
            tracing::info!("mesh triangles\n{}", self.triangle_report(shadows));
        }
        {
            let d = &mut *diagnostics;
            d.set("render.meshes.slots", self.scene.hot.len() as f64);
            d.set("render.meshes.dirty_slots", self.scene.dirty as f64);
            // Slots the serial pass took (cluster path and first uploads).
            d.set("render.meshes.serial_slots", self.deferred.len() as f64);
            // Sun cascade casters drawn this frame: the moving ones, and the still ones of the
            // static images drawn again.
            let (mut instances, mut triangles) = (0u64, 0u64);
            let cascades = self.shadow[..SKY_OCCLUSION_VIEW]
                .iter()
                .chain(&self.shadow_static[..SKY_OCCLUSION_VIEW]);
            for b in cascades.flatten() {
                let level = self
                    .meshes
                    .get(&b.key.mesh)
                    .map_or(0, |m| m.level(b.key.lod).1);
                instances += b.count as u64;
                triangles += (level / 3) as u64 * b.count as u64;
            }
            d.set("render.meshes.cascade_instances", instances as f64);
            d.set("render.meshes.cascade_triangles", triangles as f64);
            // Meshes (re)uploaded this frame: new ones, and edits of resident ones.
            d.set(
                "render.meshes.uploads",
                std::mem::take(&mut self.uploads) as f64,
            );
            d.set(
                "render.meshes.edits",
                std::mem::take(&mut self.edits) as f64,
            );
            // The shared vertex and index buffers: pages, MB reserved and MB in use.
            let (pages, reserved, used) = self.pool.usage();
            d.set("render.meshes.pool_pages", pages as f64);
            // Pipeline variants still compiling on the warm-up threads.
            d.set(
                "render.meshes.pipelines_warming",
                (self.warmup.as_ref().map_or(0, Warmup::pending)
                    + self.impostors.as_ref().map_or(0, Impostors::warming)) as f64,
            );
            // Batches (mesh and level runs of instances), before multi-draw joins them.
            let batches = [&self.opaque, &self.transparent]
                .into_iter()
                .chain(self.shadow.iter())
                .chain(self.shadow_static.iter())
                .map(Vec::len)
                .sum::<usize>();
            d.set("render.meshes.batches", batches as f64);
            // Meshes skinned on the GPU in the last frame (a pose that didn't change isn't).
            d.set("render.meshes.skinned", self.skins.skinned as f64);
            d.set("render.meshes.skins", self.skins.skins.len() as f64);
            d.set("render.meshes.pool_mb", reserved as f64 / (1 << 20) as f64);
            d.set("render.meshes.pool_used_mb", used as f64 / (1 << 20) as f64);
            // Meshes with a copy in the pool.
            d.set("render.meshes.resident", self.meshes.len() as f64);
        }
        steps.publish(Some(diagnostics), gpu);
    }

    fn compute(&mut self, encoder: &mut wgpu::CommandEncoder, ctx: &FrameContext) {
        // First: every pass after it (shadows, prepass, the view, bakes) draws the posed
        // vertices.
        let meshes = &self.meshes;
        self.skins.encode(ctx.gpu, encoder, &self.pool, |index| {
            meshes.get(&index).map(|m| (m.pool, m.version))
        });
        if let Some(impostors) = &mut self.impostors
            && let Some(bake) = impostors.pending()
            && let Some(mesh) = self.meshes.get(&bake.mesh)
            && let Some((vertex, index)) = self.pool.buffers(mesh.pool.page)
            && let Some(materials) = &self.material_group
            && let Some(textures) = self
                .texture_sets
                .get(bake.textures as usize)
                .and_then(Option::as_ref)
                .or_else(|| self.texture_sets.first().and_then(Option::as_ref))
        {
            impostors.encode(
                ctx.gpu,
                encoder,
                &self.shader_features.mesh_constants(),
                ctx.frame_group,
                materials,
                &textures.group,
                vertex,
                index,
                &mesh.pool,
            );
        }
        if let Some(clusters) = &mut self.clusters {
            clusters.encode_culling(encoder);
        }
        if let Some(vt) = &mut self.vt {
            vt.encode(encoder);
        }
    }

    fn draw(&self, phase: RenderPhase, pass: &mut wgpu::RenderPass<'_>, _ctx: &FrameContext) {
        let batches = match phase {
            RenderPhase::Opaque => &self.opaque,
            RenderPhase::Transparent => &self.transparent,
            RenderPhase::Sky => return,
        };
        let (Some(group), Some(instances)) = (&self.material_group, &self.instances) else {
            return;
        };
        let clusters = self
            .clusters
            .as_ref()
            .filter(|c| phase == RenderPhase::Opaque && c.is_active());
        let impostors = match phase {
            RenderPhase::Opaque => self.impostor_view,
            _ => (0, 0),
        };
        if batches.is_empty() && clusters.is_none() && impostors.1 == 0 {
            return;
        }
        pass.set_bind_group(1, group, &[]);
        pass.set_vertex_buffer(1, instances.buffer.slice(..));
        self.draw_batches(
            pass,
            batches,
            |p| self.pipelines.get(p as usize).and_then(Option::as_ref),
            |_| true,
        );
        if let Some(i) = &self.impostors {
            i.draw(pass, impostors, false);
        }
        if let Some(clusters) = clusters {
            clusters.draw_scene(pass, |set| self.texture_group(set));
        }
    }

    fn draw_prepass(&self, pass: &mut wgpu::RenderPass<'_>, _ctx: &FrameContext) {
        let (Some(group), Some(instances)) = (&self.material_group, &self.instances) else {
            return;
        };
        let clusters = self.clusters.as_ref().filter(|c| c.is_active());
        if self.opaque.is_empty() && clusters.is_none() && self.impostor_view.1 == 0 {
            return;
        }
        pass.set_bind_group(1, group, &[]);
        pass.set_vertex_buffer(1, instances.buffer.slice(..));
        self.draw_batches(
            pass,
            &self.opaque,
            |p| {
                self.prepass_pipelines
                    .get(p as usize)
                    .and_then(Option::as_ref)
            },
            |_| true,
        );
        if let Some(i) = &self.impostors {
            i.draw(pass, self.impostor_view, true);
        }
        if let Some(clusters) = clusters {
            clusters.draw_prepass(pass, |set| self.texture_group(set));
        }
    }

    fn after_prepass(
        &mut self,
        encoder: &mut wgpu::CommandEncoder,
        depth: &wgpu::TextureView,
        ctx: &FrameContext,
    ) -> bool {
        self.clusters
            .as_mut()
            .is_some_and(|c| c.encode_late(ctx.gpu, encoder, depth))
    }

    fn draw_prepass_late(&self, pass: &mut wgpu::RenderPass<'_>, _ctx: &FrameContext) {
        let Some(group) = &self.material_group else {
            return;
        };
        let Some(clusters) = self.clusters.as_ref().filter(|c| c.is_active()) else {
            return;
        };
        pass.set_bind_group(1, group, &[]);
        clusters.draw_prepass_late(pass, |set| self.texture_group(set));
    }

    fn draw_shadow(&self, pass: &mut wgpu::RenderPass<'_>, cascade: usize, _ctx: &FrameContext) {
        self.draw_shadow_view(
            pass,
            &self.shadow[cascade],
            cascade,
            self.impostor_shadow[cascade],
            true,
        );
    }

    fn draw_far_shadow(&self, pass: &mut wgpu::RenderPass<'_>, _ctx: &FrameContext) {
        self.draw_shadow_view(
            pass,
            &self.shadow[FAR_SHADOW_MAP],
            FAR_SHADOW_CLUSTERS,
            self.impostor_shadow[FAR_SHADOW_MAP],
            true,
        );
    }

    fn draw_shadow_static(&self, pass: &mut wgpu::RenderPass<'_>, map: usize, _ctx: &FrameContext) {
        let view = if map == FAR_SHADOW_MAP {
            FAR_SHADOW_CLUSTERS
        } else {
            map
        };
        self.draw_shadow_view(
            pass,
            &self.shadow_static[map],
            view,
            self.impostor_shadow_static[map],
            false,
        );
    }

    fn shadow_static_changed(&self, map: usize) -> bool {
        self.static_dirty.get(map).copied().unwrap_or(false)
            || self.static_waiting.get(map).copied().unwrap_or(false)
    }

    fn stats(&self) -> FeatureStats {
        self.stats
    }

    fn clusters_drawn(&self) -> u32 {
        self.clusters.as_ref().map_or(0, |c| c.stats().clusters)
    }

    fn describe(&self) -> serde_json::Value {
        serde_json::json!({
            "gpu_meshes": self.meshes.len(),
            "meshes_with_lods": self.meshes.values().filter(|m| m.errors().next().is_some()).count(),
            "mesh_pool": self.pool.describe(),
            "texture_sets": self.texture_sets.iter().filter(|s| s.is_some()).count(),
            "materials": self.material_data.len(),
            "opaque_batches": self.opaque.len(),
            "transparent_batches": self.transparent.len(),
            "shadow_batches": self.shadow.iter().map(|s| s.len()).collect::<Vec<_>>(),
            "shadow_static_batches": self.shadow_static.iter().map(|s| s.len()).collect::<Vec<_>>(),
            "impostors": self.impostors.as_ref().map_or(0, Impostors::count),
            "impostor_atlas_bc7": self.impostors.as_ref().is_some_and(Impostors::compressed),
            "impostors_in_view": self.impostor_view.1,
            "impostors_fading": self.impostors_fading,
            "lods_fading": self.lods_fading,
            "virtual_geometry": self.clusters.as_ref().map(ClusterRenderer::describe),
            "virtual_textures": self.vt.as_ref().map(VirtualTextureSystem::describe),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Other crates bind `MeshInstance::layout()` next to their own vertex data at locations 11
    /// and up (the skinning feature does), so the shared layout must stay at 4–10.
    #[test]
    fn the_shared_instance_layout_leaves_locations_above_10_free() {
        let shared = MeshInstance::layout();
        assert!(
            shared
                .attributes
                .iter()
                .all(|a| (4..=10).contains(&a.shader_location))
        );
        let motion = MeshInstance::layout_with_motion();
        assert_eq!(motion.array_stride, shared.array_stride);
        assert!(motion.attributes.iter().any(|a| a.shader_location == 13));
    }
}
