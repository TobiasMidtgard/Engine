/// What a texture set binds in one slot.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Bound {
    /// An uploaded image: its [`ImageTexture::id`] (a new upload gets a new one).
    Image(u64),
    /// A map of a generated preset: the generated set's id.
    Generated(u64),
    /// A virtual texture: its id in the virtual texture cache (the slot binds the default
    /// texture).
    Virtual(u8),
}

/// Which images (by index) and which preset (at which size) a texture set binds.
type TextureSetKey = ([Option<u32>; TEXTURE_SLOTS], Option<(MaterialPreset, u32)>);

/// A group-2 bind group for one combination of images.
struct TextureSet {
    group: wgpu::BindGroup,
    key: TextureSetKey,
    /// What is actually bound per slot; `None` = default texture (no image, or not loaded yet).
    bound: [Option<Bound>; TEXTURE_SLOTS],
    /// `VirtualTextureSystem::bind_generation` it was built with.
    vt_generation: u64,
    last_used: u64,
}

/// The generated map a preset puts in a texture slot (none for emissive).
fn preset_map(set: &MaterialTextures, slot: usize) -> Option<&wgpu::TextureView> {
    match slot {
        0 => Some(&set.base_color),
        1 => Some(&set.normal),
        2 | 4 => Some(&set.orm),
        5 => Some(&set.height),
        _ => None,
    }
}

impl TextureSet {
    /// Whether every image it asks for is bound (none is still loading).
    fn complete(&self) -> bool {
        self.key
            .0
            .iter()
            .zip(&self.bound)
            .all(|(want, bound)| want.is_none() || bound.is_some())
    }

    /// Texture-present flag bits for the slots bound to real images.
    fn flags(&self) -> u32 {
        self.bound
            .iter()
            .enumerate()
            .filter(|(_, b)| b.is_some())
            .fold(0, |f, (i, _)| f | (TEXTURE_FLAG_BASE << i))
    }

    /// Virtual texture ids per slot, packed as `GpuMaterial::flags[1]` (slots 0-3) and
    /// `flags[2]` (slots 4-5), 8 bits each.
    fn virtual_ids(&self) -> (u32, u32) {
        let mut words = (0u32, 0u32);
        for (slot, b) in self.bound.iter().enumerate() {
            if let Some(Bound::Virtual(id)) = b {
                let shift = (slot as u32 % 4) * 8;
                if slot < 4 {
                    words.0 |= (*id as u32) << shift;
                } else {
                    words.1 |= (*id as u32) << shift;
                }
            }
        }
        words
    }
}

